/**
 * art-488-model-replication-diff.kernel.mjs
 * Model Replication Diff — independently recomputes a model's reported outputs
 * from a declared model specification (coefficients, transform, intercept) and
 * a stated input record set, then diffs the recomputation against the model's
 * own reported outputs within a caller-supplied tolerance. Pure decision
 * kernel — no DOM, no window, no Date.now(), no Math.random().
 *
 * SCOPE FENCE (MODELVAL-REPLICATION-BUILD-SPEC.md): this kernel replicates
 * stated outputs and diffs them. It NEVER opines on conceptual soundness,
 * assumption reasonableness, or fitness for use. If the declared model
 * specification cannot be recomputed as stated (unsupported transform, no
 * coefficients, no tolerance), the honest result is "not_replicable_as_specified"
 * with a reason — a valid, useful verdict, never something to engineer around.
 */

