// _detmath inline snippet (exp + log only) — deterministic transcendental math
// (pure-JS fdlibm), needed for the natural log in the PSI/CSI formula
// psi = sum((actual_pct - expected_pct) * ln(actual_pct / expected_pct)).
// PROVENANCE: embedded VERBATIM from rtoy/fdlibm-js (https://github.com/rtoy/fdlibm-js,
// gh-pages branch), a port of SunPro fdlibm; original SunPro / rtoy copyright headers
// preserved below. rtoy/fdlibm-js is BSD-2-Clause (c) 2014 rtoy; embedded SunPro
// routines carry "Copyright (C) Sun Microsystems, Inc." under the SunPro freely-granted
// permissive notice. Zero dependency, zero network. PURPOSE (OCG SPEC Sec 18.5): browser
// V8, Worker V8, QuickJS-wasm and the RV32IM zkVM guest each route Math.exp/log to a
// DIFFERENT libm, so engine transcendentals are NOT bit-reproducible across surfaces
// (only + - * / sqrt are IEEE-bit-portable). This pure-JS fdlibm port removes the engine
// libm from the path so this kernel's execution_hash is identical on every surface.
// Trimmed from chaingraph/kernels/_detmath.bundle.mjs (GENERATED by
// scratchpad/build_detmath.mjs) to just the exp/log sections this kernel needs.
const _detmath = (function () {
'use strict';

function _DoubleHi(f) {
    var buf = new ArrayBuffer(8);
    (new Float64Array(buf))[0] = f;
    var hi = (new Uint32Array(buf))[1];
    return hi | 0;
}

function _DoubleLo(f) {
    var buf = new ArrayBuffer(8);
    (new Float64Array(buf))[0] = f;
    var lo = (new Uint32Array(buf))[0];
    return lo;
}

function _ConstructDouble(high, low)
{
    var buf = new ArrayBuffer(8);
    (new Uint32Array(buf))[1] = high;
    (new Uint32Array(buf))[0] = low;
    return new Float64Array(buf)[0];
}

/* ===== exp (exp.js) ===== */
const exp = (function () {
// ====================================================
// Copyright (C) 2004 by Sun Microsystems, Inc. All rights reserved.
//
// Permission to use, copy, modify, and distribute this
// software is freely granted, provided that this notice
// is preserved.
// ====================================================

var half = [0.5, -0.5];
var twom1000= 9.33263618503218878990e-302;
var o_threshold=  7.09782712893383973096e+02;
var u_threshold= -7.45133219101941108420e+02;
var ln2hi   =[ 6.93147180369123816490e-01,
                  -6.93147180369123816490e-01];
var ln2lo   =[ 1.90821492927058770002e-10,
                  -1.90821492927058770002e-10];
var invln2 =  1.44269504088896338700e+00;
var P1   =  1.66666666666666019037e-01;
var P2   = -2.77777777770155933842e-03;
var P3   =  6.61375632143793436117e-05;
var P4   = -1.65339022054652515390e-06;
var P5   =  4.13813679705723846039e-08;

function exp (x) {
    var k = 0;
    var hi = 0;
    var lo = 0;

    var hx = _DoubleHi(x);
    var xsb = (hx >> 31) & 1;
    hx &= 0x7fffffff;

    if (hx >= 0x40862e42) {
        if (hx >= 0x7ff00000) {
            if (isNaN(x)) {
                return x;
            }
            return (xsb == 0) ? x : 0;
        }
        if (x > o_threshold)
            return Infinity;
        if (x < u_threshold) {
            return 0;
        }
    }

    if (hx > 0x3fd62e42) {
        if (hx < 0x3ff0a2b2) {
            if (x == 1) {
                return Math.E;
            }
            hi = x - ln2hi[xsb];
            lo = ln2lo[xsb];
            k = 1 - xsb - xsb;
        } else {
            k = (invln2 * x + half[xsb]) | 0;
            var t = k;
            hi = x - t * ln2hi[0];
            lo = t * ln2lo[0];
        }
        x = hi - lo;
    } else if (hx < 0x3e300000) {
        return 1 + x;
    } else {
        k = 0;
    }

    var t = x * x;
    var c = x - t*(P1+t*(P2+t*(P3+t*(P4+t*P5))));

    if (k == 0) {
        return 1 - ((x*c)/(c - 2) - x);
    }
    var y = 1 - ((lo-(x*c)/(2.0-c))-hi);

    if (k >= -1021) {
        y = _ConstructDouble((k << 20) + _DoubleHi(y), _DoubleLo(y));
        return y;
    } else {
        y = _ConstructDouble(((k + 1000) << 20) + _DoubleHi(y), _DoubleLo(y));
        y = y * twom1000;
        return y;
    }
}
return exp;
})();

/* ===== log (log.js) ===== */
const log = (function () {
// ====================================================
// Copyright (C) 1993 by Sun Microsystems, Inc. All rights reserved.
//
// Developed at SunSoft, a Sun Microsystems, Inc. business.
// Permission to use, copy, modify, and distribute this
// software is freely granted, provided that this notice
// is preserved.
// ====================================================

var ln2_hi  =  6.93147180369123816490e-01;
var ln2_lo  =  1.90821492927058770002e-10;
var two54   =  1.80143985094819840000e+16;
var Lg1 = 6.666666666666735130e-01;
var Lg2 = 3.999999999940941908e-01;
var Lg3 = 2.857142874366239149e-01;
var Lg4 = 2.222219843214978396e-01;
var Lg5 = 1.818357216161805012e-01;
var Lg6 = 1.531383769920937332e-01;
var Lg7 = 1.479819860511658591e-01;

function log(x) {
    var hx = _DoubleHi(x);
    var lx = _DoubleLo(x);

    var k = 0;

    if (hx < 0x00100000) {
        if (((hx & 0x7fffffff) | lx) == 0)
            return -Infinity;
        if (hx<0) return NaN;
        k -= 54;
        x *= two54;
        hx = _DoubleHi(x);
    }

    if (hx >= 0x7ff00000)
        return x+x;

    k += (hx >> 20) - 1023;
    hx &= 0x000fffff;
    var i = (hx + 0x95f64) & 0x100000;

    x = _ConstructDouble(hx|(i ^ 0x3ff00000), lx);
    k += (i >> 20);
    var f = x - 1.0;
    var R;

    if ((0x000fffff & (2+hx)) < 3) {
        if (f==0) {
            if (k==0)
                return 0;
            else {
                var dk = k;
                return dk * ln2_hi + dk * ln2_lo;
            }
        }
        R = f * f * (0.5 - 0.33333333333333333 * f);
        if (k == 0)
            return f - R;
        else {
            var dk = k;
            return dk * ln2_hi - ((R - dk * ln2_lo) - f);
        }
    }

    var s = f / (2.0 + f);
    var dk = k;
    var z = s * s;

    i = hx - 0x6147a;
    var j = 0x6b851 - hx;

    var w = z * z;
    var t1= w * (Lg2 + w * (Lg4 + w * Lg6));
    var t2= z * (Lg1 + w * (Lg3 + w * (Lg5 + w * Lg7)));

    i |= j;

    R = t2 + t1;

    if (i > 0) {
        var hfsq = 0.5 * f * f;
        if (k == 0)
            return f - (hfsq - s * (hfsq + R));
        else
            return dk * ln2_hi - ((hfsq - (s * (hfsq + R) + dk * ln2_lo)) - f);
    } else {
        if (k == 0)
            return f - s * (f - R);
        else
            return dk * ln2_hi - ((s * (f - R) - dk * ln2_lo) - f);
    }
}
return log;
})();

return { exp: exp, log: log };
})();
/* ===== END deterministic transcendental math ===== */

const TOOL_ID = 'art-489-model-test-battery';
const TOOL_VERSION = '1.0.0';

export const meta = {
  tool_id: TOOL_ID, tool_version: TOOL_VERSION,
  mcp_name: 'run_model_test_battery',
  mandate_type: 'compliance_control', gpu: false,
};

function s(v) { return String(v == null ? '' : v).trim(); }
function n(v, d) { const x = Number(v); return Number.isFinite(x) ? x : d; }
function isFiniteNum(v) { return typeof v === 'number' && Number.isFinite(v); }

const PSI_EPS = 1e-6;

// ── Gini / KS from scored binary outcomes ──────────────────────────────────
function computeDiscrimination(scored) {
  if (!Array.isArray(scored) || scored.length === 0) return null;
  const rows = [];
  for (const r of scored) {
    const score = isFiniteNum(r && r.score) ? r.score : null;
    const outcome = r && (r.outcome === 1 || r.outcome === true) ? 1 : (r && (r.outcome === 0 || r.outcome === false) ? 0 : null);
    if (score === null || outcome === null) continue;
    rows.push({ score, outcome });
  }
  if (rows.length === 0) return null;
  const sorted = rows.slice().sort((a, b) => b.score - a.score);
  let nPos = 0, nNeg = 0;
  for (const r of sorted) { if (r.outcome === 1) nPos++; else nNeg++; }
  if (nPos === 0 || nNeg === 0) return null; // no discrimination is computable with one class

  let cumP = 0, cumN = 0, auc = 0, maxKS = 0, prevFPR = 0, prevTPR = 0;
  for (const r of sorted) {
    if (r.outcome === 1) cumP++; else cumN++;
    const tpr = cumP / nPos, fpr = cumN / nNeg;
    auc += (fpr - prevFPR) * (tpr + prevTPR) / 2;
    const ks = Math.abs(tpr - fpr);
    if (ks > maxKS) maxKS = ks;
    prevFPR = fpr; prevTPR = tpr;
  }
  const gini = 2 * auc - 1;
  return { auc: +auc.toFixed(10), gini: +gini.toFixed(10), ks: +maxKS.toFixed(10), n_scored: rows.length, n_positive: nPos, n_negative: nNeg };
}

// ── PSI / CSI: sum((actual_pct - expected_pct) * ln(actual_pct/expected_pct)) ──
function computeStabilityIndex(bins) {
  if (!Array.isArray(bins) || bins.length === 0) return null;
  let expTotal = 0, actTotal = 0;
  for (const b of bins) { expTotal += n(b && b.expected_count, 0); actTotal += n(b && b.actual_count, 0); }
  if (expTotal <= 0 || actTotal <= 0) return null;

  let index = 0;
  const detail = [];
  for (const b of bins) {
    const ep = n(b && b.expected_count, 0) / expTotal;
    const ap = n(b && b.actual_count, 0) / actTotal;
    const epf = ep <= 0 ? PSI_EPS : ep;
    const apf = ap <= 0 ? PSI_EPS : ap;
    const contribution = (apf - epf) * _detmath.log(apf / epf);
    index += contribution;
    detail.push({
      bin: s(b && b.bin) || null,
      expected_pct: +ep.toFixed(8),
      actual_pct: +ap.toFixed(8),
      contribution: +contribution.toFixed(10),
    });
  }
  return { index: +index.toFixed(10), detail };
}

// ── Back-test + calibration: predicted vs actual rate per declared bin ──────
function computeBinComparison(bins) {
  if (!Array.isArray(bins) || bins.length === 0) return null;
  let maxAbsDiff = 0;
  const detail = [];
  for (const b of bins) {
    const predicted_rate = isFiniteNum(b && b.predicted_rate) ? b.predicted_rate : null;
    const actual_rate = isFiniteNum(b && b.actual_rate) ? b.actual_rate : null;
    if (predicted_rate === null || actual_rate === null) continue;
    const abs_diff = Math.abs(actual_rate - predicted_rate);
    if (abs_diff > maxAbsDiff) maxAbsDiff = abs_diff;
    detail.push({
      bin: s(b && b.bin) || null,
      predicted_rate,
      actual_rate,
      n: Number.isFinite(n(b && b.n, null)) ? Math.trunc(n(b && b.n, 0)) : null,
      abs_diff: +abs_diff.toFixed(10),
    });
  }
  if (detail.length === 0) return null;
  return { max_abs_diff: +maxAbsDiff.toFixed(10), detail };
}

// Assemble one policy-gated test result. `available` carries the computed
// {metric_value, detail} or null if the underlying data was insufficient.
function gateTest({ name, standard_name, threshold_field, thresholds, available, metric_value, comparison, detail, unavailable_reason }) {
  const threshold = isFiniteNum(thresholds[threshold_field]) ? thresholds[threshold_field] : null;
  const base = { name, standard_name, threshold_field, threshold, comparison };
  if (!available) {
    return { ...base, metric_value: null, detail: detail ?? null, result: 'skipped_insufficient_data', reason: unavailable_reason };
  }
  if (threshold === null) {
    return { ...base, metric_value, detail: detail ?? null, result: 'skipped_no_threshold', reason: 'threshold not supplied in policy input' };
  }
  const pass = comparison === '>=' ? metric_value >= threshold : metric_value <= threshold;
  return { ...base, metric_value, detail: detail ?? null, result: pass ? 'pass' : 'breach' };
}

export function compute(pp) {
  pp = pp || {};
  const as_of_date = s(pp.as_of_date) || null;
  const threshold_version = s(pp.threshold_version) || null;
  const thresholdsIn = pp.thresholds && typeof pp.thresholds === 'object' ? pp.thresholds : {};
  const thresholds_applied = {
    gini_min: isFiniteNum(thresholdsIn.gini_min) ? thresholdsIn.gini_min : null,
    ks_min: isFiniteNum(thresholdsIn.ks_min) ? thresholdsIn.ks_min : null,
    psi_max: isFiniteNum(thresholdsIn.psi_max) ? thresholdsIn.psi_max : null,
    csi_max: isFiniteNum(thresholdsIn.csi_max) ? thresholdsIn.csi_max : null,
    calibration_max_diff: isFiniteNum(thresholdsIn.calibration_max_diff) ? thresholdsIn.calibration_max_diff : null,
  };

  const discrimination = pp.discrimination && typeof pp.discrimination === 'object' ? pp.discrimination : {};
  const stability = pp.stability && typeof pp.stability === 'object' ? pp.stability : {};
  const backtest = pp.backtest && typeof pp.backtest === 'object' ? pp.backtest : {};

  const disc = computeDiscrimination(discrimination.scored_outcomes);
  const psi = computeStabilityIndex(stability.population_bins);

  // CSI: characteristic_bins grouped by `characteristic`, one stability index per group.
  const charBinsIn = Array.isArray(stability.characteristic_bins) ? stability.characteristic_bins : [];
  const byCharacteristic = new Map();
  for (const b of charBinsIn) {
    const c = s(b && b.characteristic) || '(unlabeled)';
    if (!byCharacteristic.has(c)) byCharacteristic.set(c, []);
    byCharacteristic.get(c).push(b);
  }
  let csi = null;
  if (byCharacteristic.size > 0) {
    const perCharacteristic = [];
    let maxCsi = null;
    for (const [characteristic, bins] of byCharacteristic) {
      const r = computeStabilityIndex(bins);
      if (!r) continue;
      perCharacteristic.push({ characteristic, index: r.index, detail: r.detail });
      if (maxCsi === null || r.index > maxCsi) maxCsi = r.index;
    }
    if (perCharacteristic.length > 0) csi = { index: maxCsi, per_characteristic: perCharacteristic };
  }

  const backtestCmp = computeBinComparison(backtest.bins);

  const tests = [
    gateTest({
      name: 'gini_coefficient', standard_name: 'Gini coefficient',
      threshold_field: 'gini_min', thresholds: thresholds_applied, comparison: '>=',
      available: !!disc, metric_value: disc ? disc.gini : null,
      detail: disc ? { auc: disc.auc, n_scored: disc.n_scored, n_positive: disc.n_positive, n_negative: disc.n_negative } : null,
      unavailable_reason: 'discrimination.scored_outcomes missing, empty, or single-class (need both outcome=0 and outcome=1)',
    }),
    gateTest({
      name: 'ks_statistic', standard_name: 'Kolmogorov-Smirnov statistic',
      threshold_field: 'ks_min', thresholds: thresholds_applied, comparison: '>=',
      available: !!disc, metric_value: disc ? disc.ks : null,
      detail: disc ? { n_scored: disc.n_scored, n_positive: disc.n_positive, n_negative: disc.n_negative } : null,
      unavailable_reason: 'discrimination.scored_outcomes missing, empty, or single-class (need both outcome=0 and outcome=1)',
    }),
    gateTest({
      name: 'population_stability_index', standard_name: 'Population Stability Index (PSI)',
      threshold_field: 'psi_max', thresholds: thresholds_applied, comparison: '<=',
      available: !!psi, metric_value: psi ? psi.index : null, detail: psi ? psi.detail : null,
      unavailable_reason: 'stability.population_bins missing, empty, or both snapshot totals are zero',
    }),
    gateTest({
      name: 'characteristic_stability_index', standard_name: 'Characteristic Stability Index (CSI, max across characteristics)',
      threshold_field: 'csi_max', thresholds: thresholds_applied, comparison: '<=',
      available: !!csi, metric_value: csi ? csi.index : null, detail: csi ? csi.per_characteristic : null,
      unavailable_reason: 'stability.characteristic_bins missing, empty, or both snapshot totals are zero for every characteristic',
    }),
    gateTest({
      name: 'calibration', standard_name: 'Calibration (predicted vs actual rate per bin, max abs diff)',
      threshold_field: 'calibration_max_diff', thresholds: thresholds_applied, comparison: '<=',
      available: !!backtestCmp, metric_value: backtestCmp ? backtestCmp.max_abs_diff : null, detail: backtestCmp ? backtestCmp.detail : null,
      unavailable_reason: 'backtest.bins missing, empty, or no bin had both predicted_rate and actual_rate',
    }),
  ];

  const tests_run = tests.filter(t => t.result === 'pass' || t.result === 'breach').length;
  const tests_passed = tests.filter(t => t.result === 'pass').length;
  const tests_breached = tests.filter(t => t.result === 'breach').length;
  const tests_skipped_no_threshold = tests.filter(t => t.result === 'skipped_no_threshold').length;
  const tests_skipped_insufficient_data = tests.filter(t => t.result === 'skipped_insufficient_data').length;

  const compliance_flags = ['MDVL_BATTERY_CALCULATED'];
  for (const t of tests) {
    if (t.result === 'breach') compliance_flags.push(`MDVL_BREACH_${t.name.toUpperCase()}`);
    if (t.result === 'skipped_no_threshold') compliance_flags.push(`MDVL_SKIPPED_NO_THRESHOLD_${t.name.toUpperCase()}`);
  }
  if (tests_breached > 0) compliance_flags.push('MDVL_BATTERY_HAS_BREACH');
  if (tests_run === 0) compliance_flags.push('MDVL_BATTERY_NO_TESTS_RUN');

  return {
    output_payload: {
      as_of_date,
      threshold_version,
      thresholds_applied,
      tests,
      back_test: backtestCmp ? { per_bin: backtestCmp.detail } : null,
      tests_run,
      tests_passed,
      tests_breached,
      tests_skipped_no_threshold,
      tests_skipped_insufficient_data,
    },
    compliance_flags,
  };
}

export async function buildArtifact(pp, { now, parent_hashes = [], parent_tool_ids = [], chain_depth = 0 } = {}) {
  const { output_payload, compliance_flags } = compute(pp);
  const hash = await executionHash(pp, output_payload);
  return {
    '@context': 'https://ainumbers.co/chaingraph/context/v0.3/context.jsonld',
    chaingraph_version: '0.4.0',
    mandate_type: meta.mandate_type,
    tool_id: TOOL_ID,
    tool_version: TOOL_VERSION,
    generated_at: now ?? null,
    execution_hash: hash,
    chain: { parent_hashes, parent_tool_ids, chain_depth },
    policy_parameters: pp,
    output_payload,
    compliance_flags,
    compute_mode: 'server',
    compute_proof_ready: 'deferred',
    audit_signature: { payloadType: 'application/vnd.openchain.graph+json;version=0.4', payload: '', signatures: [] },
  };
}
