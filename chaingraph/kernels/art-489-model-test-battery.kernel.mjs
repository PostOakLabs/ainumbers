/**
 * art-489-model-test-battery.kernel.mjs
 * Model Test Battery — the deterministic-given-data quantitative validation
 * tests: discriminatory power (Gini / KS), population and characteristic
 * stability (PSI / CSI), back-test outcome-vs-predicted with declared binning,
 * and calibration comparison (predicted vs actual rate per bin). Each test is
 * compared against a POLICY-SUPPLIED threshold; the kernel never chooses or
 * hardcodes a threshold. If a threshold is missing for a requested test, that
 * test is skipped and the artifact says so. Pure decision kernel — no DOM, no
 * window, no Date.now(), no Math.random().
 *
 * SCOPE FENCE (MODELVAL-REPLICATION-BUILD-SPEC.md): this kernel reports
 * per-test pass/breach against caller-declared thresholds only. It NEVER
 * emits a validation opinion (conceptual soundness, fitness for use).
 */

