#!/usr/bin/env node
/**
 * scripts/gen-changelog.mjs — public CHANGELOG.md, derived from LOCAL GIT
 * HISTORY ONLY (CHANGELOG-1, CONTRACT Amendment A12).
 *
 * ── THE LETTER THIS PRESERVES ───────────────────────────────────────────────
 * "Pure function of tracked inputs" (the regen doctrine, SO #35): this
 * generator reads (a) the repository's own git history and (b) the committed
 * seed `scripts/changelog-seed.json`. It performs NO network I/O — not a
 * fetch, not an API call — so a regeneration is reproducible from the checkout
 * alone, byte-for-byte at the same HEAD. Idempotent: no wall clock anywhere in
 * the output; the rendered bytes depend only on history + seed.
 *
 * ── SOURCES: what becomes an entry ──────────────────────────────────────────
 *   · merge commits on `main`'s FIRST-PARENT history (PR merges carry their
 *     PR number; direct branch pushes that themselves contained merge commits
 *     are keyed by commit);
 *   · annotated/lightweight TAGS reachable from HEAD — every reachable tag
 *     MUST be classified in the seed (`heading` or `ignore` + reason), which
 *     is how a future release tag turns into a version section without
 *     editing this script.
 *   ⛔ board/ and ainumbers-internal/ are NEVER consulted (never a source);
 *     the only inputs are `git log` / `git tag` against THIS repository and
 *     the committed seed.
 *   · EXCLUDED from the walk: GitHub's merge-queue SYNTHETIC test-merges
 *     (subject exactly "Merge <sha> into <sha>"). They are re-created with a
 *     new sha on every grouped evaluation, never land, and are superseded by
 *     the real landing merge — which classifies per the standing contract.
 *
 * ── UNDER-REPORTING, STATED NOT HIDDEN (the header scope note) ──────────────
 * Direct pushes to `main` and post-merge regeneration commits (the
 * derived-artifacts bot) do not create merge commits, so they produce NO
 * entry. The generated file says this in its header — the changelog is a
 * merge-PR view of history, and most recent landings are direct pushes.
 * TAGS are under-reported too, in one specific environment: GitHub's
 * ephemeral merge-group queue checkout fetches NO tag refs, so `git tag
 * --merged` errors there. Tag listing is therefore TOLERANT of failure
 * (listTags): an environment that cannot list tags renders with an EMPTY tag
 * set — no tag version scopes, merge-commit entries unaffected, limitation
 * named in run output and in the header scope note. Same by-construction
 * disclosure discipline as direct pushes; never a crash, never a guessed tag.
 * The fail-closed tag CLASSIFICATION (every listed tag must be in the seed)
 * is unchanged — tolerance is about the listing succeeding, not about
 * classifying less.
 *
 * ── FAIL-CLOSED FORWARD ─────────────────────────────────────────────────────
 * Every entry the history yields MUST be classified in the seed (section +
 * public title). An unclassified entry (typically: a merge commit that landed
 * after the seed was last touched) EXITS 1 and names it — it never renders a
 * guessed or raw-subject line, because merge subjects carry internal row IDs.
 * Historical entries were classified exactly once, into the seed. Standing
 * contract: a PR that lands a merge commit appends its own seed line.
 * The seed entry keys are `pr-<number>` (PR merges) or `c-<first 10 hex of
 * the commit hash>` (every other merge) — stable across clones by
 * construction.
 *
 * ── THE LEAK GATE (this file's second job) ──────────────────────────────────
 * The generated bytes are scanned for internal-language vocabulary BEFORE they
 * are written: board row IDs (SCREAMING-KEYWORD-1 shapes), standing-order
 * references, owner names, orchestrator/session role nouns, model-vendor
 * names, and internal workspace paths. Any hit EXITS 1 quoting the line and
 * the pattern class — `scripts/copy-hallmarks.mjs` scans .html only, so this
 * gate is the ONLY leak net CHANGELOG.md has. A hit is fixed in the SEED
 * (curated public title), never by editing the generated file.
 *
 * Output: CHANGELOG.md at the repository root (published via
 * scripts/published-dirs.json rootPages; single-writer via
 * scripts/derived-artifacts.mjs COVERED id 'changelog').
 *
 * Usage:
 *   node scripts/gen-changelog.mjs          # render + write CHANGELOG.md
 *   node scripts/gen-changelog.mjs --check  # freshness gate: exit 1 if stale
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gitEnv } from './_git-env-lib.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const REPO = resolve(HERE, '..');
export const OUT_PATH = resolve(REPO, 'CHANGELOG.md');
export const SEED_PATH = resolve(HERE, 'changelog-seed.json');
const CHECK = process.argv.includes('--check');
const REPO_URL = 'https://github.com/PostOakLabs/ainumbers';

// ── THE LEAK GATE ───────────────────────────────────────────────────────────
// Three vocabulary classes named by CHANGELOG-1: row IDs, owner/session
// vocabulary, vendor vocabulary — plus internal workspace paths and
// standing-order references, which are the same class of secret by content.
// Case-sensitive on purpose: the leak shapes are uppercase row IDs and proper
// nouns; case-insensitive matching false-positived on ordinary public prose
// during calibration (e.g. "session" inside the public "idv session receipt"
// node family).
/** Public tokens a row-ID-shaped string may legitimately contain. */
export const PUBLIC_TOKEN_ALLOWLIST = [
  'ISO-20022', 'SHA-256', 'T420-427', // public standard / algorithm / tool-number range
];
export const LEAK_PATTERNS = [
  {
    name: 'row-id',
    // Two shapes, one class. (a) needs a second ALPHA-bearing segment so public
    // token shapes that end in digits (SHA-256, ISO-20022, tool range T420-427)
    // never match — those are separately allowlisted for defense in depth.
    // (b) catches the WORD-<number> row shape (CHANGELOG-1, CARD-1, RUN-1-2)
    // with a ≥2-letter head, which is too loose for (a) without eating single
    // capital-letter standards prefixes (Y-9C stays public on purpose).
    re: /\b[A-Z][A-Z0-9]*-[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*-\d+\b/g,
    why: 'board row / wave IDs (e.g. SOME-ROW-1) are internal',
  },
  {
    name: 'row-id',
    re: /\b[A-Z]{2,}[A-Z0-9]*-\d+\b/g,
    why: 'board row / wave IDs (e.g. SOMEWORD-1) are internal',
  },
  { name: 'standing-order-ref', re: /\bSO #\d+\b/g, why: 'standing-orders references are internal' },
  { name: 'owner-name', re: /\bTim\b/g, why: 'owner names are internal' },
  {
    name: 'orchestration-role',
    re: /\b(?:ORCH|orchestrator|checkoff|worktree|0xAlpha|7F)\b/g,
    why: 'orchestrator/session role nouns are internal',
  },
  {
    name: 'model-vendor',
    re: /\b(?:GLM|ZCode|Z\.ai|Claude|Anthropic|OpenAI|ChatGPT|Codex|Copilot|Gemini)\b/g,
    why: 'model/vendor names are internal',
  },
  {
    name: 'internal-path',
    re: /(?:\bboard\/|ainumbers-internal|\.wt\/|\bclaim\.mjs|\bcheckoff\.mjs)/g,
    why: 'internal workspace paths are internal',
  },
];

/** Scan rendered text; returns [{ line, no, hit, name, why }]. Pure. */
export function collectLeaks(text) {
  const hits = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    // Strip allowlisted PUBLIC tokens before matching — a line is never
    // skipped wholesale, so a real leak beside a public token still reds.
    let line = lines[i];
    for (const t of PUBLIC_TOKEN_ALLOWLIST) line = line.split(t).join('·'.repeat(t.length));
    for (const p of LEAK_PATTERNS) {
      p.re.lastIndex = 0;
      let m;
      while ((m = p.re.exec(line))) {
        hits.push({ line: lines[i], no: i + 1, hit: m[0], name: p.name, why: p.why });
      }
    }
  }
  return hits;
}

// ── GIT (local only; env scrubbed per GIT-ENV-LEAK-SWEEP-1) ─────────────────
function git(args) {
  return execSync(`git ${args}`, { cwd: REPO, env: gitEnv(), encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
}

/**
 * GitHub merge-queue SYNTHETIC test-merge subject (anchored, exact): the
 * queue's evaluation of a grouped PR produces "Merge <sha> into <sha>" — a
 * commit that is re-created with a NEW sha on every evaluation and NEVER
 * lands. Requiring its classification fail-closes on an unknowable hash each
 * round and cannot converge (measured across three queue runs on PR #2010),
 * so the walk EXCLUDES this exact shape as known-synthetic. Every other
 * unclassified merge still fails closed; the REAL landing merge (PR-shaped or
 * otherwise) classifies per the A12 standing contract in the next landing's
 * hop.
 */
export const QUEUE_TEST_MERGE_RE = /^Merge [0-9a-f]{7,40} into [0-9a-f]{7,40}$/;

/**
 * Parse first-parent merge-commit log lines → { merges, skippedSynthetic }.
 * Pure — takes the log text, spawns nothing — which is what lets the
 * self-test drive the skip rule against fixture lines without git.
 */
export function parseMerges(logText) {
  const merges = [];
  let skippedSynthetic = 0;
  for (const l of logText.split('\n').filter(Boolean)) {
    const [hash, short, date, ...rest] = l.split('\t');
    const subject = rest.join('\t');
    if (QUEUE_TEST_MERGE_RE.test(subject)) {
      skippedSynthetic++;
      continue;
    }
    const m = subject.match(/^Merge pull request #(\d+) from /);
    merges.push({
      hash,
      short,
      date,
      pr: m ? Number(m[1]) : null,
      key: m ? `pr-${Number(m[1])}` : `c-${hash.slice(0, 10)}`,
    });
  }
  return { merges, skippedSynthetic };
}

/** First-parent merges at HEAD, synthetic queue test-merges excluded. */
export function collectMerges() {
  return parseMerges(git('log --first-parent --merges --date=short --pretty=format:%H%x09%h%x09%ad%x09%s'));
}

const TAG_GIT_ARGS = 'tag --merged HEAD --sort=-creatordate --format=%(refname:short)%09%(creatordate:short)';

function parseTagList(out) {
  return out.split('\n').filter(Boolean).map((l) => {
    const i = l.indexOf('\t');
    return { name: l.slice(0, i), date: l.slice(i + 1) };
  });
}

/**
 * Tags reachable from HEAD, TOLERANT of tag-less checkouts (MERGEGROUP
 * TAG-FIX, measured in run 35692678563): GitHub's ephemeral merge-group queue
 * branch fetches NO tag refs, so this git call ERRORS there and the whole
 * changelog gate — and derived-artifacts --regen with it — went red on a
 * healthy tree. Tags are version-SCOPE decoration only: merge-commit entries
 * classify independently via their subjects, so on listing failure this
 * returns an EMPTY tag set and the caller CONTINUES, naming the environment
 * limitation in run output (never silent, never a crash, never a guessed
 * tag). The fail-closed tag CLASSIFICATION contract is untouched — a tag
 * that IS listed must still be in the seed. `runner` is injectable so the
 * self-test can simulate the tag-less failure without spawning git.
 * Returns { tags, source: 'git' | 'tag-less-environment', error? }.
 */
export function listTags(runner) {
  const run = runner || ((args) => git(args));
  try {
    return { tags: parseTagList(run(TAG_GIT_ARGS)), source: 'git' };
  } catch (e) {
    return {
      tags: [],
      source: 'tag-less-environment',
      error: String((e && e.message) || e).split('\n')[0],
    };
  }
}

function escMd(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/**
 * Render the changelog body. Pure: same (merges, tags, seed) → same bytes.
 * Fail-closed: throws on an unclassified merge entry, an unclassified tag, or
 * a seed section that does not exist — never guesses.
 */
export function renderChangelog(merges, tags, seed) {
  const sections = seed.sections;
  if (!Array.isArray(sections) || sections.length === 0) {
    throw new Error('seed.sections must be a non-empty ordered array');
  }
  const entries = seed.entries || {};
  const tagNotes = seed.tags || {};

  const unclassified = merges.filter((m) => !entries[m.key]);
  if (unclassified.length) {
    const lines = unclassified.map((m) =>
      `  ${m.key}  (${m.date})  ${m.pr !== null ? 'merge of PR #' + m.pr : 'non-PR merge ' + m.short}` +
      `\n      classify in scripts/changelog-seed.json: "entries"."${m.key}" = { "section": "...", "title": "..." }`);
    throw new Error(
      `FAIL-CLOSED: ${unclassified.length} unclassified merge entr${unclassified.length === 1 ? 'y' : 'ies'} ` +
      `in first-parent history — the changelog never renders a guessed line:\n${lines.join('\n')}\n` +
      `Standing contract (Amendment A12): the PR that lands a merge commit appends its own seed line.`);
  }
  const unknownTags = tags.filter((t) => !tagNotes[t.name]);
  if (unknownTags.length) {
    throw new Error(
      `FAIL-CLOSED: ${unknownTags.length} reachable tag(s) unclassified in scripts/changelog-seed.json ("tags"):\n` +
      unknownTags.map((t) => `  ${t.name} (${t.date}) — add { "heading": "..." } or { "ignore": "<reason>" }`).join('\n'));
  }
  const badSections = Object.entries(entries).filter(([, v]) => !sections.includes(v.section));
  if (badSections.length) {
    throw new Error(
      `FAIL-CLOSED: seed entries name sections outside seed.sections (${sections.join(', ')}):\n` +
      badSections.map(([k, v]) => `  ${k} -> "${v.section}"`).join('\n'));
  }

  // Version scopes: Unreleased (everything newer than the newest classified
  // tag) plus one scope per classified tag, bounded by the next-older tag's
  // date. Output order: Unreleased first, then newest → oldest.
  const activeTags = tags
    .filter((t) => tagNotes[t.name].heading)
    .map((t) => ({ ...t, heading: tagNotes[t.name].heading }))
    .sort((a, b) => (a.date < b.date ? 1 : -1));
  const scopes = [];
  if (activeTags.length === 0) {
    scopes.push({ heading: 'Unreleased', ceil: null, floor: null });
  } else {
    scopes.push({ heading: 'Unreleased', ceil: null, floor: activeTags[0].date });
    for (let i = 0; i < activeTags.length; i++) {
      scopes.push({
        heading: activeTags[i].heading,
        ceil: activeTags[i].date,
        floor: i + 1 < activeTags.length ? activeTags[i + 1].date : null,
      });
    }
  }

  const bySection = new Map(sections.map((s) => [s, []]));
  for (const m of merges) {
    const e = entries[m.key];
    const scope = scopes.find((sc) =>
      (sc.ceil === null || m.date <= sc.ceil) && (sc.floor === null || m.date > sc.floor));
    if (scope) bySection.get(e.section).push({ ...m, title: e.title, scope: scope.heading });
  }

  const out = [];
  out.push('# Changelog');
  out.push('');
  out.push(`Notable changes to [AINumbers](https://ainumbers.co) — the OpenChainGraph compliance suite (source: [${REPO_URL}](${REPO_URL})).`);
  out.push('');
  out.push('> **Scope of this file.** GENERATED from this repository\'s local git history —');
  out.push('> first-parent merge commits into `main`, plus repository tags — by');
  out.push('> `node scripts/gen-changelog.mjs`, with classifications committed in');
  out.push('> `scripts/changelog-seed.json`. It is a pure function of tracked inputs: no');
  out.push('> network, no wall clock, and **no hand edits** (edit the seed, then regenerate).');
  out.push('> **It under-reports by construction:** only merge commits and tags are visible');
  out.push('> to it, so changes landed by **direct pushes to `main`** — including the');
  out.push('> post-merge regeneration commits of the derived-artifacts bot — do not create');
  out.push('> entries. Recent landings have been largely direct pushes. Tags are under-');
  out.push('> reported in one environment too: a **tag-less CI checkout** (GitHub\'s ephemeral');
  out.push('> merge-group queue fetches no tag refs) renders with **no tag version scopes**,');
  out.push('> while merge-commit entries still classify. Classified entries');
  out.push('> are fail-closed forward: a merge commit missing from the seed fails the');
  out.push('> generator (and the freshness gate) until it is classified there.');
  out.push('');
  for (const scope of scopes) {
    const body = sections
      .map((s) => ({ name: s, items: bySection.get(s).filter((it) => it.scope === scope.heading) }))
      .filter((s) => s.items.length);
    if (!body.length) continue;
    out.push(`## ${scope.heading}`);
    out.push('');
    for (const s of body) {
      out.push(`### ${s.name}`);
      out.push('');
      for (const it of s.items.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0))) {
        const ref = it.pr !== null
          ? ` ([#${it.pr}](${REPO_URL}/pull/${it.pr}))`
          : ` ([\`${it.short}\`](${REPO_URL}/commit/${it.hash}))`;
        out.push(`- ${it.date} — ${escMd(it.title)}${ref}`);
      }
      out.push('');
    }
  }
  out.push('<!-- GENERATED FILE — DO NOT HAND-EDIT. Regenerate: node scripts/gen-changelog.mjs -->');
  return out.join('\n') + '\n';
}

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

function main() {
  if (git('rev-parse --is-shallow-repository').trim() === 'true') {
    fail('gen-changelog: this checkout is a SHALLOW clone — first-parent history is truncated, so the fail-closed seed comparison would red spuriously. Fetch full history (fetch-depth: 0).');
  }
  const { merges, skippedSynthetic } = collectMerges();
  if (skippedSynthetic) {
    console.log(`gen-changelog: skipped ${skippedSynthetic} synthetic merge-queue test-merge commit(s) (known-synthetic, never lands; the real landing merge classifies per the A12 standing contract).`);
  }
  const { tags, source: tagSource, error: tagError } = listTags();
  if (tagSource === 'tag-less-environment') {
    // MERGEGROUP TAG-FIX: named, never silent — the same disclosure discipline
    // as the header scope note. Merge-commit entries are unaffected.
    console.error(`gen-changelog: TAG-LESS ENVIRONMENT — tag listing failed (${tagError}); proceeding with 0 tag scopes. Merge-commit entries are unaffected; tag version headings are under-reported in this checkout (see the header scope note).`);
  }
  const seed = JSON.parse(readFileSync(SEED_PATH, 'utf8'));
  const tagNotes = seed.tags || {};
  let text;
  try {
    text = renderChangelog(merges, tags, seed);
  } catch (e) {
    fail(`gen-changelog: ${e.message}`);
  }

  // THE LEAK GATE — on the exact bytes about to be written/read.
  const leaks = collectLeaks(text);
  if (leaks.length) {
    console.error(`gen-changelog LEAK GATE: ${leaks.length} internal-language hit(s) in the rendered changelog — RED:`);
    for (const h of leaks.slice(0, 20)) {
      console.error(`  line ${h.no} [${h.name}] matched "${h.hit}" — ${h.why}`);
      console.error(`    > ${h.line.trim()}`);
    }
    if (leaks.length > 20) console.error(`  … and ${leaks.length - 20} more`);
    console.error('Fix in scripts/changelog-seed.json (curated public title for the named entry), then regenerate. Never hand-edit CHANGELOG.md.');
    process.exit(1);
  }

  if (CHECK) {
    const current = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : '';
    if (current !== text) {
      fail('gen-changelog --check FAIL: CHANGELOG.md is stale relative to history+seed. Run: node scripts/gen-changelog.mjs' +
        (tagSource === 'tag-less-environment'
          ? ' (note: this checkout is TAG-LESS; if the committed file carries tag version scopes, this diff is environmental — regenerate from a full checkout with tags fetched)'
          : ''));
    }
    console.log(`gen-changelog --check: OK (${merges.length} classified merge entries, ${tags.length} reachable tags${tagSource === 'tag-less-environment' ? ', TAG-LESS environment tolerated' : ''}, leak gate green).`);
    process.exit(0);
  }
  writeFileSync(OUT_PATH, text, 'utf8');
  const voided = tags.filter((t) => tagNotes[t.name] && tagNotes[t.name].ignore);
  console.log(`gen-changelog: written (${merges.length} merge entries across ${seed.sections.length} sections; ${tags.length} reachable tags${tagSource === 'tag-less-environment' ? ' [TAG-LESS environment: listing failed, scopes skipped]' : ''}${voided.length ? `, ${voided.length} ignored per seed` : ''}; leak gate green).`);
}

// Run only on direct execution. The self-test imports this module's pure
// functions and must not trigger a write (or a --check exit) as an import
// side effect.
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main();
}
