#!/usr/bin/env node
/**
 * scripts/gen-fact-stamps.mjs — FACT-STAMPS-PILOT-1
 *
 * WHAT. Fills the `<!-- FACT-STAMP:START -->` … `<!-- FACT-STAMP:END -->` sentinel
 * region on each pilot page with one visible display line per dated fact:
 *
 *     Verified YYYY-MM-DD against <source name>
 *
 * …where the date is the sidecar entry's own `verified_on` and the link points at
 * its `source_url`. The sidecar is data/bank-fact-freshness.json (REVERIFY-BANK-1,
 * watched by check-bank-fact-freshness.mjs's 120-day gate) — the SAME file is the
 * single source for both the freshness gate and the stamps, so a re-verification
 * (one verified_on edit) refreshes the visible stamp by rerunning this generator.
 *
 * WHY A REGION AND NOT INLINE TEXT. The pilot pages carry regulatory facts that
 * age (IRS Pub 15-T editions, SSA wage bases, SWIFT standards releases, SEC/Fed
 * docket state). Hand-typed "as of" lines rot silently; a generated region makes
 * the visible stamp a pure function of the sidecar the freshness gate already
 * watches (SO #0b: automate it, dated observation, never a promise about future
 * updates — SO #0).
 *
 * NEVER A KERNEL SURFACE. Stamps are page display chrome. They live OUTSIDE any
 * inline compute block covered by the kernel-digest sentinel and OUTSIDE any
 * result/payload block, so no date or source ever reaches a kernel's
 * output_payload, a node shard, or a fixture — execution_hash, the §18 journal
 * and all proofs are untouched by design (BUILD-SPEC E "Never").
 *
 * MODES.
 *   node scripts/gen-fact-stamps.mjs           write (default): fill every region
 *   node scripts/gen-fact-stamps.mjs --check   exit 1 if any region differs from
 *                                              what the sidecar implies
 *
 * DERIVATION (SO #34 — the sidecar is the SSOT, the page never attests itself).
 *   page for an entry:  node "art-X" → chaingraph/art-X.html, else tools/<node>.html
 *   display name:       SOURCE_NAMES below, keyed by source_url host, falling
 *                       back to the bare host (schema stays unchanged)
 * Both directions are errors, never silent: an entry whose page lacks a region,
 * a region whose page has no entry, a missing page file, or a duplicated region.
 *
 * DETERMINISTIC. No wall clock anywhere: the stamp date is each entry's
 * verified_on, so write mode is a pure function of the sidecar and the page
 * bytes and --check is stable in CI. Zero-dependency (node builtins only,
 * STANDING ORDER #10).
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const DATA_PATH = resolve(REPO, 'data/bank-fact-freshness.json');

const OPEN = '<!-- FACT-STAMP:START -->';
const CLOSE = '<!-- FACT-STAMP:END -->';

const CHECK = process.argv.includes('--check');

// source_url host → link text for the "against <name>" display line. A bare host
// is the fallback, so a new source needs no generator edit to stamp correctly.
const SOURCE_NAMES = new Map([
  ['www.ssa.gov', 'SSA'],
  ['www.irs.gov', 'IRS'],
  ['www.swift.com', 'Swift'],
  ['www.sec.gov', 'SEC'],
  ['www.frbservices.org', 'Federal Reserve Financial Services'],
]);

const GEN_COMMENT =
  '<!-- Generated by scripts/gen-fact-stamps.mjs from data/bank-fact-freshness.json. ' +
  'Dated observations only, never promises about future updates (SO #0). ' +
  'Do not hand-edit; run the generator. -->';

const STAMP_STYLE =
  "font-family:'JetBrains Mono',monospace;font-size:.62rem;color:var(--muted);margin:10px 0";
const LINK_STYLE = 'color:var(--teal)';

function fail(msg) {
  console.error(`✗ gen-fact-stamps: ${msg}`);
  process.exit(1);
}

/** chaingraph nodes live at chaingraph/<node>.html; tool pages at tools/<node>.html. */
function pagePathForNode(node) {
  return String(node || '').startsWith('art-')
    ? `chaingraph/${node}.html`
    : `tools/${node}.html`;
}

function sourceName(url) {
  let host = String(url || '');
  try {
    host = new URL(url).host;
  } catch {
    fail(`entry source_url is not a valid URL: ${url}`);
  }
  return SOURCE_NAMES.get(host) ?? host;
}

/** The one visible display line for a fact — a dated observation, nothing more. */
function stampLine(entry) {
  const { verified_on: date, source_url: url } = entry;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(date || ''))) {
    fail(`entry ${entry.id} has no YYYY-MM-DD verified_on — a stamp needs a retrieval date`);
  }
  return (
    `<div class="fact-stamp" style="${STAMP_STYLE}">` +
    `Verified ${date} against ` +
    `<a href="${url}" style="${LINK_STYLE}">${sourceName(url)}</a>` +
    `</div>`
  );
}

/** The exact bytes this generator wants between the delimiters for these entries. */
function regionContent(entries) {
  return (
    '\n' +
    GEN_COMMENT +
    '\n' +
    entries.map(stampLine).join('\n') +
    '\n'
  );
}

/** [startIdx, endIdx] of the one region in html, or null; errors on duplicates. */
function findRegion(html, rel) {
  const open = html.indexOf(OPEN);
  if (open === -1) return null;
  const close = html.indexOf(CLOSE, open);
  if (close === -1) fail(`${rel} carries ${OPEN} with no matching ${CLOSE}`);
  const next = html.indexOf(OPEN, open + OPEN.length);
  if (next !== -1) fail(`${rel} carries more than one FACT-STAMP region — exactly one is allowed`);
  return [open, close + CLOSE.length];
}

// ── load the sidecar ──────────────────────────────────────────────────────────────
const data = JSON.parse(readFileSync(DATA_PATH, 'utf8'));
const entries = Array.isArray(data.entries) ? data.entries : [];
if (!entries.length) fail('data/bank-fact-freshness.json has no entries — nothing to stamp');

// ── group entries per page ────────────────────────────────────────────────────────
const pages = new Map(); // rel path → entries[]
for (const entry of entries) {
  if (!entry.node) fail(`entry ${entry.id} has no node field`);
  const rel = pagePathForNode(entry.node);
  if (!pages.has(rel)) pages.set(rel, []);
  pages.get(rel).push(entry);
}

// ── collect every page carrying a region (bidirectional coverage) ────────────────
const regionPages = new Set();
for (const dir of ['chaingraph', 'tools']) {
  for (const f of readdirSync(resolve(REPO, dir))) {
    if (!f.endsWith('.html')) continue;
    const rel = `${dir}/${f}`;
    const html = readFileSync(resolve(REPO, dir, f), 'utf8');
    if (html.includes(OPEN) || html.includes(CLOSE)) regionPages.add(rel);
  }
}

const problems = [];
for (const rel of pages.keys()) {
  if (!existsSync(resolve(REPO, rel))) problems.push(`entry page ${rel} does not exist`);
  else if (!regionPages.has(rel)) problems.push(`entry page ${rel} carries no FACT-STAMP region`);
}
for (const rel of regionPages) {
  if (!pages.has(rel)) problems.push(`page ${rel} carries a FACT-STAMP region but no sidecar entry names its node`);
}
if (problems.length) {
  for (const p of problems) console.error(`  • ${p}`);
  fail(`${problems.length} sidecar/page mapping problem(s)`);
}

// ── fill or check every region ────────────────────────────────────────────────────
let written = 0;
let clean = 0;
for (const [rel, pageEntries] of pages) {
  const path = resolve(REPO, rel);
  const html = readFileSync(path, 'utf8');
  const span = findRegion(html, rel);
  const before = html.slice(span[0], span[1]);
  const after = OPEN + regionContent(pageEntries) + CLOSE;
  if (before === after) {
    clean += 1;
    continue;
  }
  if (CHECK) {
    console.error(`  • ${rel} — FACT-STAMP region differs from what data/bank-fact-freshness.json implies`);
    console.error(`      fix: node scripts/gen-fact-stamps.mjs (write mode), then commit`);
  } else {
    writeFileSync(path, html.slice(0, span[0]) + after + html.slice(span[1]));
    written += 1;
    console.log(`  ✓ ${rel} — stamped ${pageEntries.length} fact(s)`);
  }
}

if (CHECK) {
  // `clean` counts regions already correct; any drift reported above exits 1.
  const drifted = pages.size - clean;
  if (drifted) fail(`FACT-STAMP check FAILED — ${drifted} of ${pages.size} page(s) drifted`);
  console.log(`✓ FACT-STAMP check clean — ${clean} page(s) match the sidecar (${entries.length} fact(s) stamped)`);
  process.exit(0);
}

console.log(`✓ gen-fact-stamps: ${written} page(s) written, ${clean} already correct, ${entries.length} fact(s) across ${pages.size} page(s)`);
