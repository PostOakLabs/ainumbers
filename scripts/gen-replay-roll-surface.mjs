#!/usr/bin/env node
// gen-replay-roll-surface.mjs — REPLAY-ROLL-SURFACE-1 (2026-11-22).
//
// The generated witness-roll section on the determinism explainer
// (chaingraph/determinism-attestation-explainer.html), rendered from
// data/replay-witness-roll.json by the single writer, spliced between
// REPLAY-ROLL-SURFACE markers the way gen-errata-snapshot.mjs splices its
// regions. The roll itself stays prAbsentOk (derived-artifacts.mjs id
// 'replay-witness-roll'); this entry owns ONLY the page region.
//
//   node scripts/gen-replay-roll-surface.mjs           # splice the region (regen command)
//   node scripts/gen-replay-roll-surface.mjs --check   # freshness: exit 1 if the region would change
//
// Rules the section must not break (build spec sections 3d, 6, 7; row fence):
//   - the phrase "reproduced by N distinct GitHub accounts", never
//     "independent", "audited", "certified" or "verified by the community";
//   - zero outside witnesses is shown as zero, never hidden;
//   - the three summary figures go through <!--COUNT:...--> count sentinels
//     registered in scripts/counts.mjs (replay.*), never hand-typed. The
//     per-module table cells are the roll rendered verbatim by this writer,
//     so they are derived too; only the quoted figures need sentinels. The
//     page is deliberately NOT in verify-counts.mjs's scan list (same choice
//     vintage-calendar.html made at birth): as a REGION_WRITER page a PR
//     carries the sentinel lines, and this --check pins every region byte.
//   - each witness shows login, account creation date, runtimes and bundle
//     link; per module, the house line and the outside line, never summed;
//   - the page says a witness can leave by deleting the fork or its
//     attestations (static prose beside the region, not generated);
//   - no em-dash or en-dash in anything rendered, no build codes, and every
//     roll-sourced string is HTML-escaped and shape-validated before render.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = resolve(HERE, '..');
export const ROLL_REL = join('data', 'replay-witness-roll.json');
export const PAGE_REL = join('chaingraph', 'determinism-attestation-explainer.html');
export const ROLL_SCHEMA = 'ainumbers.co/replay-witness-roll/v1';
export const ROLL_COUNT_KEYS = ['replay.modules', 'replay.accounts', 'replay.disagreements'];

const START_PREFIX = '<!-- REPLAY-ROLL-SURFACE:START';
const END_MARKER = '<!-- REPLAY-ROLL-SURFACE:END -->';
export const START_LINE = START_PREFIX +
  ' (generated by scripts/gen-replay-roll-surface.mjs from data/replay-witness-roll.json;' +
  ' DO NOT hand-edit: main\'s derived regen owns this region) -->';

const CHECK = process.argv.includes('--check');

// Refusal: throws (so the self-test can assert on it); main() is the only place
// that converts it into an exit code.
function die(msg) {
  throw new Error(`gen-replay-roll-surface: REFUSED ${msg}`);
}

const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// Shape validation, fail closed. Every string that reaches the page passes
// here: a malformed roll must stop the writer, never render half a claim.
const DASH_RE = /[‐‒–—―]/;   // hyphen bullets excluded; en/em/hbar refused
const LOGIN_RE = /^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38}[A-Za-z0-9])?$/;   // GitHub login shape
const FORK_RE = /^[A-Za-z0-9][A-Za-z0-9.-]*\/[A-Za-z0-9][A-Za-z0-9.-]*$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const RUNTIME_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
const VECTOR_ID_RE = /^[A-Za-z0-9][A-Za-z0-9._:/-]*$/;   // "art-9/v1", "module:sha256:<hex>"
const URL_RE = /^https:\/\/[A-Za-z0-9][A-Za-z0-9._~:/?#[\]@!$&'()*+,;=%-]*$/;

function str(v, where, re = null) {
  if (typeof v !== 'string' || !v.trim()) die(`${where}: expected a non-empty string`);
  if (DASH_RE.test(v)) die(`${where}: carries an en/em dash character; render plain text only`);
  if (re && !re.test(v)) die(`${where}: ${JSON.stringify(v)} fails its shape rule`);
  return v;
}

export function loadRoll(roll) {
  if (!roll || typeof roll !== 'object') die('roll: not an object');
  if (roll.schema !== ROLL_SCHEMA) die(`roll.schema: expected ${ROLL_SCHEMA}, got ${JSON.stringify(roll.schema)}`);
  if (!roll.modules || typeof roll.modules !== 'object' || Array.isArray(roll.modules)) die('roll.modules: expected an object');
  for (const key of Object.keys(roll.modules)) {
    const m = roll.modules[key];
    str(key, 'module key', /^[A-Za-z0-9][A-Za-z0-9._:-]*$/);
    if (!m || typeof m !== 'object') die(`modules[${key}]: not an object`);
    for (const line of ['house', 'outside']) {
      if (!m[line] || typeof m[line] !== 'object') die(`modules[${key}].${line}: missing`);
      for (const n of ['agree', 'disagree', 'accounts_agree', 'accounts_disagree']) {
        if (m[line][n] !== undefined && (!Number.isInteger(m[line][n]) || m[line][n] < 0)) die(`modules[${key}].${line}.${n}: expected a non-negative integer`);
      }
      if (line === 'house' && typeof m[line].signed !== 'boolean') die(`modules[${key}].house.signed: expected a boolean`);
      if (line === 'outside') {
        if (!Array.isArray(m[line].runtimes)) die(`modules[${key}].outside.runtimes: expected an array`);
        for (const r of m[line].runtimes) str(r, `modules[${key}].outside.runtimes[]`, RUNTIME_RE);
      }
    }
  }
  if (!Array.isArray(roll.witnesses)) die('roll.witnesses: expected an array');
  roll.witnesses.forEach((w, i) => {
    const where = `witnesses[${i}]`;
    str(w?.account, `${where}.account`, LOGIN_RE);
    str(w?.account_created, `${where}.account_created`, /^unknown$|^\d{4}-\d{2}-\d{2}$/);
    str(w?.fork, `${where}.fork`, FORK_RE);
    if (w?.result !== 'agree' && w?.result !== 'disagree') die(`${where}.result: expected agree or disagree`);
    if (!Array.isArray(w?.runtimes)) die(`${where}.runtimes: expected an array`);
    for (const r of w.runtimes) str(r, `${where}.runtimes[]`, RUNTIME_RE);
    str(w?.bundle_url, `${where}.bundle_url`, URL_RE);
  });
  if (!Array.isArray(roll.disagreements)) die('roll.disagreements: expected an array');
  roll.disagreements.forEach((d, i) => {
    const where = `disagreements[${i}]`;
    str(d?.account, `${where}.account`, LOGIN_RE);
    str(d?.fork, `${where}.fork`, FORK_RE);
    if (!Array.isArray(d?.vector_ids)) die(`${where}.vector_ids: expected an array`);
    for (const v of d.vector_ids) str(v, `${where}.vector_ids[]`, VECTOR_ID_RE);
    str(d?.bundle_url, `${where}.bundle_url`, URL_RE);
  });
  str(roll.wording, 'roll.wording');
  return roll;
}

// The three quoted figures. Registered in scripts/counts.mjs deriveCounts()
// under the same keys from the same file; the self-test pins the parity, and
// every render emits them as <!--COUNT:...--> sentinels, never bare digits.
export function rollCounts(roll) {
  const witnesses = Array.isArray(roll?.witnesses) ? roll.witnesses : [];
  return {
    'replay.modules': Object.keys(roll?.modules ?? {}).length,
    'replay.accounts': new Set(witnesses.filter((w) => w?.result === 'agree' && typeof w?.account === 'string').map((w) => w.account)).size,
    'replay.disagreements': Array.isArray(roll?.disagreements) ? roll.disagreements.length : 0,
  };
}

const sentinel = (key, counts) => `<!--COUNT:${key}-->${counts[key]}<!--/COUNT-->`;

function witnessRow(w) {
  const runtimes = w.runtimes.length ? esc(w.runtimes.join(', ')) : 'none recorded';
  return `<tr><td class="m"><a href="https://github.com/${esc(w.account)}">${esc(w.account)}</a></td>` +
    `<td class="m">${esc(w.account_created)}</td>` +
    `<td class="m"><a href="https://github.com/${esc(w.fork)}">${esc(w.fork)}</a></td>` +
    `<td><span class="v ${w.result === 'agree' ? 'v-ok' : 'v-no'}">${w.result}</span></td>` +
    `<td class="m">${runtimes}</td>` +
    `<td class="m"><a href="${esc(w.bundle_url)}">attestation bundle</a></td></tr>`;
}

function disagreementRow(d) {
  const ids = d.vector_ids.slice(0, 12).join(', ');
  const more = d.vector_ids.length > 12 ? ` and ${d.vector_ids.length - 12} more` : '';
  return `<tr><td class="m"><a href="https://github.com/${esc(d.account)}">${esc(d.account)}</a></td>` +
    `<td class="m"><a href="https://github.com/${esc(d.fork)}">${esc(d.fork)}</a></td>` +
    `<td class="m">${esc(ids)}${more ? esc(more) : ''}</td>` +
    `<td class="m"><a href="${esc(d.bundle_url)}">attestation bundle</a></td></tr>`;
}

function moduleRow(key, m) {
  const house = m.house ?? {};
  const out = m.outside ?? {};
  const signed = house.signed
    ? '<span class="v v-ok">signed</span>'
    : '<span class="v v-esc">unsigned</span>';
  const runtimes = (out.runtimes ?? []).length ? esc(out.runtimes.join(', ')) : 'none yet';
  return `<tr><td class="m">${esc(key)}</td>` +
    `<td class="m">${house.agree ?? 0}/${house.disagree ?? 0}</td>` +
    `<td>${signed}</td>` +
    `<td class="m">${out.accounts_agree ?? 0}/${out.accounts_disagree ?? 0}</td>` +
    `<td class="m">${runtimes}</td></tr>`;
}

// The rendered region. Pure: same roll bytes in, same region bytes out, so the
// splice is a fixpoint and --check is exact.
export function renderRegion(rollInput) {
  const roll = loadRoll(rollInput);
  const counts = rollCounts(roll);
  const modules = Object.keys(roll.modules).sort();
  const L = [];
  L.push(START_LINE);
  L.push('<p>The roll is rendered from <a href="../data/replay-witness-roll.json">data/replay-witness-roll.json</a> (schema <code>' + ROLL_SCHEMA + '</code>). The corpus window covers ' + sentinel('replay.modules', counts) + ' modules, and it is reproduced by ' + sentinel('replay.accounts', counts) + ' distinct GitHub accounts. Recorded disagreements: ' + sentinel('replay.disagreements', counts) + '.</p>');
  L.push('<p class="detail">' + esc(roll.wording) + '</p>');
  if (roll.witnesses.length === 0) {
    L.push('<p>No witness record exists yet, so the account count above is zero. Zero is the current state of the roll, not a gap in the page: every module below still carries its house line, and the roll grows only from verified runs.</p>');
  } else {
    L.push('<h3>Witness records</h3>');
    L.push('<div class="runs-scroll"><table class="runs">');
    L.push('<thead><tr><th>Account</th><th>Account created</th><th>Fork</th><th>Result</th><th>Runtimes</th><th>Bundle</th></tr></thead>');
    L.push('<tbody>');
    for (const w of roll.witnesses) L.push(witnessRow(w));
    L.push('</tbody></table></div>');
  }
  if (roll.disagreements.length === 0) {
    L.push('<p>No disagreement is recorded. A verified run whose result digest differs from the agreed digest would be listed here with the differing vector ids, and it would stay in the roll rather than being dropped.</p>');
  } else {
    L.push('<h3>Disagreements</h3>');
    L.push('<p>A disagreement stays in the roll. It is never dropped, and it feeds the errata lane as a nondeterminism finding.</p>');
    L.push('<div class="runs-scroll"><table class="runs">');
    L.push('<thead><tr><th>Account</th><th>Fork</th><th>Differing vector ids</th><th>Bundle</th></tr></thead>');
    L.push('<tbody>');
    for (const d of roll.disagreements) L.push(disagreementRow(d));
    L.push('</tbody></table></div>');
  }
  L.push('<details class="roll-modules"><summary>The per-module roll: ' + sentinel('replay.modules', counts) + ' modules, each with its house line and its outside line</summary>');
  L.push('<div class="runs-scroll"><table class="runs">');
  L.push('<thead><tr><th>Module</th><th>House agree/disagree</th><th>House signature</th><th>Outside accounts agree/disagree</th><th>Outside runtimes</th></tr></thead>');
  L.push('<tbody>');
  for (const key of modules) L.push(moduleRow(key, roll.modules[key]));
  L.push('</tbody></table></div></details>');
  // The region ends with the END marker itself (the gen-errata-snapshot.mjs
  // shape): no trailing newline, so the page's own newline after the marker
  // terminates the line and spliceRegion stays a fixpoint.
  L.push(END_MARKER);
  return L.join('\n');
}

export function spliceRegion(text, replacement, where) {
  const a = text.indexOf(START_PREFIX);
  const b = text.indexOf(END_MARKER);
  if (a === -1 || b === -1 || b < a) die(`${where}: markers not found or out of order (a=${a}, b=${b})`);
  return text.slice(0, a) + replacement + text.slice(b + END_MARKER.length);
}

// Mechanical copy guards over the rendered region, the gen-vintage-calendar.mjs
// shape, plus this row's own wording bans (build spec section 6). Comments are
// chrome (the sentinel markers and the START line carry dashes of their own).
export function renderGuard(regionHtml) {
  const prose = regionHtml
    .replace(/<!--[\s\S]*?-->/g, ' ');
  if (DASH_RE.test(prose)) die('renderGuard: rendered region carries an en/em dash');
  if (/Wave \d/.test(prose) || /W-[A-G]\b/.test(prose)) die('renderGuard: rendered region carries a build code');
  if (/\bindependent\w*\b/i.test(prose)) die('renderGuard: the wording rule bans "independent"');
  if (/\baudited\b/i.test(prose)) die('renderGuard: the wording rule bans "audited"');
  if (/\bcertified\b/i.test(prose)) die('renderGuard: the wording rule bans "certified"');
  if (/verified by the community/i.test(prose)) die('renderGuard: the wording rule bans "verified by the community"');
  return regionHtml;
}

function main() {
  try {
    const rollPath = resolve(ROOT, ROLL_REL);
    let roll;
    try {
      roll = JSON.parse(readFileSync(rollPath, 'utf8'));
    } catch (e) {
      die(`${ROLL_REL} is unreadable (${e.message}); the roll is committed on main and this writer renders from it`);
    }
    const region = renderGuard(renderRegion(roll));
    const pagePath = resolve(ROOT, PAGE_REL);
    const page = readFileSync(pagePath, 'utf8');
    const next = spliceRegion(page, region, PAGE_REL);
    if (CHECK) {
      if (next === page) {
        console.log(`gen-replay-roll-surface --check: fixpoint ok (${rollCounts(roll)['replay.modules']} modules, ${rollCounts(roll)['replay.accounts']} outside account(s), ${rollCounts(roll)['replay.disagreements']} disagreement(s))`);
        return;
      }
      console.error(`gen-replay-roll-surface --check: ${PAGE_REL} region is STALE; the single writer owns it`);
      process.exit(1);
    }
    writeFileSync(pagePath, next);
    console.log(`gen-replay-roll-surface: wrote the region in ${PAGE_REL}`);
  } catch (e) {
    console.error(String(e.message ?? e).startsWith('gen-replay-roll-surface:') ? e.message : `gen-replay-roll-surface: ${e.message ?? e}`);
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
