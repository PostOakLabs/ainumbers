#!/usr/bin/env node
/**
 * scripts/apply-topic-links.mjs — TOOLS-GRAPH-BRIDGE-1
 *
 * Reads data/topic-links.json and inserts (or refreshes) a "Related" cross-link
 * block on every page listed in each topic, pointing at its topic-mates on the
 * OTHER surface (tools/ <-> chaingraph/ node <-> guide hub). Idempotent: reruns
 * replace the marker-delimited block instead of duplicating it.
 *
 * Usage: node scripts/apply-topic-links.mjs           (writes)
 *        node scripts/apply-topic-links.mjs --check   (dry-run, exit 1 if stale)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname, relative, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const checkOnly = process.argv.includes('--check')

const registry = JSON.parse(readFileSync(resolve(root, 'data/topic-links.json'), 'utf8'))

const MARK_START = '<!-- TOPIC-LINKS:start (generated by scripts/apply-topic-links.mjs — do not hand-edit) -->'
const MARK_END = '<!-- TOPIC-LINKS:end -->'

function titleOf(path) {
  const html = readFileSync(resolve(root, path), 'utf8')
  const m = html.match(/<title>([^<]*)<\/title>/)
  if (m) return m[1].split('·')[0].trim()
  return basename(path).replace(/\.html$/, '')
}

function buildBlock(selfPath, topic) {
  const selfDir = dirname(selfPath)
  const all = [
    ...topic.tool_paths.map(p => ({ p, group: 'Related tools' })),
    ...topic.node_paths.map(p => ({ p, group: 'Related on the graph' })),
    ...(topic.guide_paths || []).map(p => ({ p, group: 'Related guide' })),
  ].filter(({ p }) => p !== selfPath)

  if (all.length === 0) return null

  const groups = new Map()
  for (const { p, group } of all) {
    if (!groups.has(group)) groups.set(group, [])
    groups.get(group).push(p)
  }

  let body = ''
  for (const [group, paths] of groups) {
    const links = paths
      .map(p => {
        const href = relative(selfDir, resolve(root, p)).split('\\').join('/')
        return `<a href="${href}">${titleOf(p)}</a>`
      })
      .join(' &middot; ')
    body += `<div><span class="related-topics-label">${group}:</span> ${links}</div>`
  }

  return `${MARK_START}\n<section class="related-topics" aria-label="Related ${topic.label} pages" style="border-top:1px solid var(--border);margin-top:2rem;padding-top:1rem;font-size:0.85rem;color:var(--muted)">${body}</section>\n${MARK_END}`
}

let changed = 0
let checked = 0

for (const topic of registry.topics) {
  const allPaths = [...topic.tool_paths, ...topic.node_paths, ...(topic.guide_paths || [])]
  for (const selfPath of allPaths) {
    checked++
    const abs = resolve(root, selfPath)
    if (!existsSync(abs)) {
      console.error(`apply-topic-links: MISSING ${selfPath} (topic ${topic.key})`)
      process.exitCode = 1
      continue
    }
    const block = buildBlock(selfPath, topic)
    if (!block) continue

    let html = readFileSync(abs, 'utf8')
    const startIdx = html.indexOf(MARK_START)
    const footerIdx = html.indexOf('<footer')

    let next
    if (startIdx !== -1) {
      const endIdx = html.indexOf(MARK_END) + MARK_END.length
      next = html.slice(0, startIdx) + block + html.slice(endIdx)
    } else if (footerIdx !== -1) {
      next = html.slice(0, footerIdx) + block + '\n' + html.slice(footerIdx)
    } else {
      console.error(`apply-topic-links: no <footer> or marker in ${selfPath}, skipping`)
      continue
    }

    if (next !== html) {
      changed++
      if (checkOnly) {
        console.error(`apply-topic-links: STALE ${selfPath} (topic ${topic.key})`)
      } else {
        writeFileSync(abs, next)
      }
    }
  }
}

if (checkOnly) {
  if (changed > 0) {
    console.error(`apply-topic-links: ${changed} page(s) stale — run 'node scripts/apply-topic-links.mjs' and commit.`)
    process.exit(1)
  }
  console.log(`apply-topic-links: OK — ${checked} pages current.`)
} else {
  console.log(`apply-topic-links: wrote ${changed} of ${checked} pages.`)
}
