#!/usr/bin/env node
/**
 * scripts/migrate-chaingraph-shards.mjs — ONE-TIME CS-1 migration.
 *
 * Splits chaingraph/chaingraph.json into:
 *   chaingraph/graph/nodes/<tool_id>.json   — one file per node
 *   chaingraph/graph/chains/<name>.json     — one file per chain
 *   chaingraph/chaingraph.meta.json         — header block + MIGRATION-MODE
 *                                              raw glue text for byte-identical
 *                                              reassembly (order preserved
 *                                              verbatim; see CS-2 for the
 *                                              canonical-order flip that
 *                                              retires the `raw` block).
 *
 * Run once: node scripts/migrate-chaingraph-shards.mjs
 * Then verify: node scripts/assemble-chaingraph.mjs --check
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'
import { findTopLevelArrayBounds, splitTopLevelElements } from './_chaingraph-shard-lib.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = resolve(__dirname, '..')
const CG_PATH = resolve(root, 'chaingraph/chaingraph.json')
const NODES_DIR = resolve(root, 'chaingraph/graph/nodes')
const CHAINS_DIR = resolve(root, 'chaingraph/graph/chains')
const META_PATH = resolve(root, 'chaingraph/chaingraph.meta.json')

const raw = readFileSync(CG_PATH, 'utf8')

const nb = findTopLevelArrayBounds(raw, 'nodes')
const cb = findTopLevelArrayBounds(raw, 'chains')

const nodesInner = raw.slice(nb.openIdx + 1, nb.closeIdx)
const chainsInner = raw.slice(cb.openIdx + 1, cb.closeIdx)

const nodeSegs = splitTopLevelElements(nodesInner)
const chainSegs = splitTopLevelElements(chainsInner)

function leadWSOf(seg) {
  return seg.slice(0, seg.length - seg.trimStart().length)
}

// header: everything through the '[' that opens "nodes", plus the leading
// whitespace of the first node element (that whitespace lives outside any
// shard file, so it must be captured here, not lost)
const header = raw.slice(0, nb.openIdx + 1) + leadWSOf(nodeSegs[0])
// betweenNodesAndChains: everything from the ']' closing "nodes" through the
// '[' that opens "chains" (inclusive of both brackets), plus the leading
// whitespace of the first chain element
const betweenNodesAndChains = raw.slice(nb.closeIdx, cb.openIdx + 1) + leadWSOf(chainSegs[0])
// footer: everything from the ']' closing "chains" through EOF
const footer = raw.slice(cb.closeIdx)

if (!existsSync(NODES_DIR)) mkdirSync(NODES_DIR, { recursive: true })
if (!existsSync(CHAINS_DIR)) mkdirSync(CHAINS_DIR, { recursive: true })

const nodeOrder = []
const nodeSeparators = []
nodeSegs.forEach((seg, i) => {
  const text = seg.trim()
  const obj = JSON.parse(text)
  const id = obj.tool_id
  if (!id) throw new Error(`node ${i} has no tool_id`)
  writeFileSync(resolve(NODES_DIR, `${id}.json`), text + '\n', 'utf8')
  nodeOrder.push(id)
  if (i < nodeSegs.length - 1) {
    const nextSeg = nodeSegs[i + 1]
    const trailWS = seg.slice(seg.lastIndexOf(text) + text.length)
    const leadWS = nextSeg.slice(0, nextSeg.length - nextSeg.trimStart().length)
    nodeSeparators.push(trailWS + ',' + leadWS)
  } else {
    // trailing whitespace after the last element, before the ']'
    nodeSeparators.push(seg.slice(seg.lastIndexOf(text) + text.length))
  }
})

const chainOrder = []
const chainSeparators = []
chainSegs.forEach((seg, i) => {
  const text = seg.trim()
  const obj = JSON.parse(text)
  const name = obj.name
  if (!name) throw new Error(`chain ${i} has no name`)
  writeFileSync(resolve(CHAINS_DIR, `${name}.json`), text + '\n', 'utf8')
  chainOrder.push(name)
  if (i < chainSegs.length - 1) {
    const nextSeg = chainSegs[i + 1]
    const trailWS = seg.slice(seg.lastIndexOf(text) + text.length)
    const leadWS = nextSeg.slice(0, nextSeg.length - nextSeg.trimStart().length)
    chainSeparators.push(trailWS + ',' + leadWS)
  } else {
    chainSeparators.push(seg.slice(seg.lastIndexOf(text) + text.length))
  }
})

const meta = {
  _comment: 'GENERATED by migrate-chaingraph-shards.mjs (CS-1, one-time). Consumed by assemble-chaingraph.mjs. The `raw` block is MIGRATION-MODE glue that reproduces legacy insertion order byte-identically; CS-2 replaces it with canonical sorted-order generation and drops `raw`.',
  order: { nodes: nodeOrder, chains: chainOrder },
  raw: { header, betweenNodesAndChains, footer, nodeSeparators, chainSeparators },
}

writeFileSync(META_PATH, JSON.stringify(meta, null, 2) + '\n', 'utf8')

console.log(`Sharded ${nodeOrder.length} nodes -> ${NODES_DIR}`)
console.log(`Sharded ${chainOrder.length} chains -> ${CHAINS_DIR}`)
console.log(`Wrote meta -> ${META_PATH}`)
console.log('Next: node scripts/assemble-chaingraph.mjs --check')
