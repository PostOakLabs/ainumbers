#!/usr/bin/env node
// scripts/append-absence-lineage-record.mjs — REGISTRY-ABSENCE-TREE-BUILD-1,
// reconciled by REGISTRY-ABSENCE-LINEAGE-REBIND-1.
//
// Appends the DERIVED absence-tree record ({tree_root, key_count}) to
// chaingraph/kernels/registry-lineage-records.json — the lineage generator's
// read-only INPUT list, which rows append to and gen-registry-lineage.mjs
// itself never writes. The record is machine-derived from the recomputed tree
// (scripts/gen-registry-absence-tree.mjs's buildAbsenceTree) — never
// hand-typed — and the append is a no-op when an identical record already
// exists. Publishing afterwards is `node scripts/gen-registry-lineage.mjs`
// (one Sigsum add-leaf; manual/generated by design, see the EXCLUDED entry in
// derived-artifacts.mjs).
//
// ── LOG-AHEAD RECONCILIATION (REGISTRY-ABSENCE-LINEAGE-REBIND-1) ─────────────
// The records file and the published log can DIVERGE: a record can be
// published seat-side (gen-registry-lineage run) while its append to this
// INPUT file never lands — exactly what JCS-CANON-FIX-1 (#2132) did, leaving
// main's log one entry AHEAD of the records file (log index 33 bound root
// 8a8d, records file still ending at 32). In that state the printed remedy
// silently JAMS: the append lands in the file's next slot, the record count
// then EQUALS the published size, and gen-registry-lineage's size-only
// unchanged-since-last-publish skip (its §2.1 budget guard) refuses to anchor
// a log that would have to MOVE an already-published index — so the new root
// never binds and `gen-registry-absence-tree.mjs --check` stays red forever.
// Before appending, this script therefore RECONCILES the records file with
// the published log: entries the log carries but the file lacks are imported
// from the published entry-bundle bytes (machine-derived, never hand-typed),
// and the whole shared prefix is verified BYTE-IDENTICAL through the ONE
// canonicalizer — any divergence is an honest refusal, never a silent repair.
// The log itself stays append-only: reconciliation restores the INPUT to
// match what was ALREADY published, so the next append lands at the next LOG
// index and gen-registry-lineage's consistency gate (§2.3) cryptographically
// confirms leaf continuity before anything is published.
//
// WHY A SEPARATE SCRIPT: this write is mode-scoped row tooling, NOT the
// COVERED regen command's write. Keeping it out of
// gen-registry-absence-tree.mjs's own source keeps that file's statically
// measured write set exactly {registry/absence/tree.json}, which is what its
// COVERED entry declares (DERIVED-DECLARE-PARITY-1 / SO #47: the declared set
// and the measured set must agree by construction, not by exemption). Since
// REGISTRY-ABSENCE-LINEAGE-REBIND-1 the COVERED `registry-absence-tree` regen
// command CHAINS this script after the tree write, so a main-side regen
// commit always carries the tree TOGETHER with its binding record — the
// anchor stays deferred to gen-registry-lineage.mjs ("publishing stays a
// manual/generated run", gen-registry-absence-tree.mjs header).
//
// Usage:
//   node scripts/append-absence-lineage-record.mjs
//   node scripts/append-absence-lineage-record.mjs --verify-regen-binding
//
// `--verify-regen-binding` (LINEAGE-BINDING-REGEN-REPAIRABLE-1) is READ-ONLY:
// it never appends, reconciles or writes. It verifies the two conditions under
// which an in-flight PR's lineage binding drift is honestly regen-repairable by
// main's single-writer derived-artifacts-regen (which appends AND publishes
// after merge, publish being the step this script deliberately does not do):
//   (i)  the records file carries the published log as a BYTE-IDENTICAL prefix
//        through the one canonicalizer, with records length >= log size (a
//        records file AHEAD of the log — appended, publish pending — is fine);
//   (ii) the LAST absence record in the records file equals the tree_root and
//        key_count recomputed from the current F2 key set (what main's regen
//        appends at the next log index).
// Prints BINDING-OK / BINDING-FAIL <reason> and exits 0/1; consumed by
// check-regen-repairable.mjs's post-regen binding override.
//
// Exit codes: 0 appended, reconciled, already present, or --verify-regen-binding
// held · 1 the absence tree cannot be built, the records file has diverged from
// the published log, or --verify-regen-binding found the binding not
// regen-repairable.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSignedNote } from '../chaingraph/kernels/c2sp-tlog-verify.mjs';
import { buildAbsenceTree, absenceLineageRecord, loadKeySet, ABSENCE_ANCHOR_TYPE } from './gen-registry-absence-tree.mjs';
import { readEntryBundles, canonicalEntryBytes } from './gen-registry-lineage.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const RECORDS_PATH = resolve(REPO, 'chaingraph', 'kernels', 'registry-lineage-records.json');
const LINEAGE_DIR = resolve(REPO, 'registry', 'lineage');

function bytesEqual(a, b) {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return false;
  return true;
}

// ---------------------------------------------------------------------------
// Reconcile the INPUT list with the published log (see header). Mutates
// `records` in place; returns the number of entries imported. Refuses —
// without writing anything — if any already-listed record does not byte-match
// its published log entry, or an imported entry is not re-canonicalizable to
// its published bytes (that is corruption or a canonicalizer change, not a
// missing append).
// ---------------------------------------------------------------------------
export function reconcileRecordsFileWithPublishedLog(records, registryDir = LINEAGE_DIR, log = console.log) {
  const checkpointPath = join(registryDir, 'checkpoint');
  if (!existsSync(checkpointPath)) return 0; // nothing published yet — nothing to reconcile against
  const size = parseSignedNote(readFileSync(checkpointPath, 'utf8')).size;
  if (size === 0) return 0;
  const entries = readEntryBundles(registryDir, size);
  // Shared-prefix integrity — verified on EVERY run (in sync, publish-pending,
  // or log-ahead alike): every already-listed record must byte-match its
  // published log entry, or the file and the log have diverged beyond a
  // missing append and the §2.3 consistency gate would refuse the publish.
  const shared = Math.min(size, records.length);
  for (let i = 0; i < shared; i++) {
    if (!bytesEqual(canonicalEntryBytes(records[i]), entries[i])) {
      throw new Error(
        `append-absence-lineage-record: RECONCILIATION REFUSED — records[${i}] does not byte-match the ` +
        `published log entry ${i} (registry/lineage, size ${size}). The records file and the published log ` +
        `have diverged beyond a missing append; investigate before appending (the §2.3 consistency gate ` +
        `would refuse the publish anyway).`,
      );
    }
  }
  if (size <= records.length) return 0; // in sync, or ahead (records appended, publish pending) — the normal states
  let imported = 0;
  for (let i = records.length; i < size; i++) {
    const rec = JSON.parse(new TextDecoder().decode(entries[i]));
    if (!bytesEqual(canonicalEntryBytes(rec), entries[i])) {
      throw new Error(
        `append-absence-lineage-record: RECONCILIATION REFUSED — published log entry ${i} does not ` +
        `re-canonicalize to its own bytes (jcsStringify round-trip failed). Not importable.`,
      );
    }
    records.push(rec);
    imported++;
    log(`  reconcile: imported published log entry ${i} into the records file (published seat-side, append never landed).`);
  }
  return imported;
}

// ---------------------------------------------------------------------------
// Append (after reconciling). Exported for the test harness; the CLI main
// below is the only place with top-level side effects.
// Returns { appended, index?, existing?, imported, recordsLength }.
// ---------------------------------------------------------------------------
export async function appendAbsenceLineageRecord(opts = {}) {
  const recordsPath = opts.recordsPath || RECORDS_PATH;
  const registryDir = opts.registryDir || LINEAGE_DIR;
  const log = opts.log || (() => {});
  const reconcile = opts.reconcile !== false;

  const tree = await buildAbsenceTree(loadKeySet());
  const record = absenceLineageRecord(tree);
  const parsed = JSON.parse(readFileSync(recordsPath, 'utf8'));
  if (!Array.isArray(parsed.records)) throw new Error(`${recordsPath}: expected a top-level "records" array`);

  let imported = 0;
  if (reconcile) imported = reconcileRecordsFileWithPublishedLog(parsed.records, registryDir, log);

  const existing = parsed.records.findIndex(
    (r) => r && r.anchor_type === record.anchor_type && r.tree_root === record.tree_root && r.key_count === record.key_count,
  );
  if (existing !== -1) {
    log(`append-absence-lineage-record: lineage record already present at records[${existing}] (tree_root ${record.tree_root}, key_count ${record.key_count}) — no-op.`);
    if (imported > 0) {
      writeFileSync(recordsPath, JSON.stringify(parsed, null, 2) + '\n');
      log(`append-absence-lineage-record: wrote ${imported} reconciled entr${imported === 1 ? 'y' : 'ies'} to ${recordsPath}.`);
    }
    return { appended: false, existing, imported, recordsLength: parsed.records.length };
  }
  parsed.records.push(record);
  writeFileSync(recordsPath, JSON.stringify(parsed, null, 2) + '\n');
  const index = parsed.records.length - 1;
  log(`append-absence-lineage-record: appended absence-tree lineage record at records[${index}] (tree_root ${record.tree_root}, key_count ${record.key_count}).`);
  if (imported > 0) log(`append-absence-lineage-record: (after reconciling ${imported} published-but-never-appended log ${imported === 1 ? 'entry' : 'entries'} first).`);
  return { appended: true, index, imported, recordsLength: parsed.records.length };
}

// ---------------------------------------------------------------------------
// READ-ONLY regen-repairability of the lineage binding (LINEAGE-BINDING-REGEN-
// REPAIRABLE-1). Verifies, without writing ANYTHING: (i) the published log is
// a byte-identical prefix of the records file with records length >= log size,
// through the same canonicalizer the reconciliation above uses; (ii) the LAST
// absence record in the records file equals the {tree_root, key_count}
// recomputed from the current key set. Returns { ok, reason?, detail?,
// recordsLength?, logSize?, lastIndex?, treeRoot?, keyCount? }.
// ---------------------------------------------------------------------------
export async function verifyRegenBinding(opts = {}) {
  const recordsPath = opts.recordsPath || RECORDS_PATH;
  const registryDir = opts.registryDir || LINEAGE_DIR;
  const parsed = JSON.parse(readFileSync(recordsPath, 'utf8'));
  if (!Array.isArray(parsed.records)) throw new Error(`${recordsPath}: expected a top-level "records" array`);

  const checkpointPath = join(registryDir, 'checkpoint');
  if (!existsSync(checkpointPath)) {
    return { ok: false, reason: 'PREFIX-DIVERGENCE', detail: `no lineage checkpoint published at ${checkpointPath} — nothing to prefix against` };
  }
  const size = parseSignedNote(readFileSync(checkpointPath, 'utf8')).size;
  const entries = readEntryBundles(registryDir, size);
  if (parsed.records.length < size) {
    return {
      ok: false,
      reason: 'PREFIX-DIVERGENCE',
      detail: `records file (${parsed.records.length} entries) is SHORTER than the published log (size ${size}) — the log is ahead of its input list, which reconciliation must cure before the binding can be called regen-repairable`,
    };
  }
  for (let i = 0; i < size; i++) {
    if (!bytesEqual(canonicalEntryBytes(parsed.records[i]), entries[i])) {
      return { ok: false, reason: 'PREFIX-DIVERGENCE', detail: `records[${i}] does not byte-match published log entry ${i}` };
    }
  }

  const tree = await buildAbsenceTree(loadKeySet());
  const record = absenceLineageRecord(tree);
  let lastIndex = -1;
  for (let i = parsed.records.length - 1; i >= 0; i--) {
    if (parsed.records[i] && parsed.records[i].anchor_type === ABSENCE_ANCHOR_TYPE) { lastIndex = i; break; }
  }
  if (lastIndex === -1) {
    return { ok: false, reason: 'LAST-RECORD', detail: 'the records file contains no absence-tree record at all' };
  }
  const last = parsed.records[lastIndex];
  if (last.tree_root !== record.tree_root || last.key_count !== record.key_count) {
    return {
      ok: false,
      reason: 'LAST-RECORD',
      detail: `records[${lastIndex}] (tree_root ${last.tree_root}, key_count ${last.key_count}) != recomputed (tree_root ${record.tree_root}, key_count ${record.key_count}) — the append's dedupe did not land the current root last, so main's regen publish alone would not repair this binding`,
    };
  }
  return { ok: true, recordsLength: parsed.records.length, logSize: size, lastIndex, treeRoot: record.tree_root, keyCount: record.key_count };
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------
async function main() {
  if (process.argv.includes('--verify-regen-binding')) {
    const result = await verifyRegenBinding({ log: console.log });
    if (result.ok) {
      console.log(`append-absence-lineage-record: BINDING-OK records=${result.recordsLength} log=${result.logSize} lastIndex=${result.lastIndex} ${result.treeRoot} key_count ${result.keyCount} — published log is a byte-identical prefix of the records file and the last absence record is the recomputed root; main's regen appends AND publishes after merge, so this PR-side drift is regen-repairable (LINEAGE-BINDING-REGEN-REPAIRABLE-1).`);
      return;
    }
    console.error(`append-absence-lineage-record: BINDING-FAIL ${result.reason} — ${result.detail}`);
    process.exit(1);
  }
  const result = await appendAbsenceLineageRecord({ log: console.log });
  if (result.appended) {
    console.log('  publish it: node scripts/gen-registry-lineage.mjs   (Sigsum-anchors the new lineage head — one add-leaf)');
    if (!existsSync(resolve(REPO, 'registry', 'absence', 'tree.json'))) {
      console.log('  note: registry/absence/tree.json does not exist yet — run `node scripts/gen-registry-absence-tree.mjs --write` so the artifact matches this record.');
    }
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isMain) {
  main().catch((err) => {
    console.error(err.stack || err.message);
    process.exit(1);
  });
}
