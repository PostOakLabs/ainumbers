#!/usr/bin/env node
/**
 * gen-session-root-fixtures.mjs — COMPOSER-PLAN-AND-ROOT-WEBMCP-1, parity gate B fixture source.
 *
 * THE one script that generates repo/data/session-root-fixtures.json: >= 5 ordered
 * execution-hash lists with their expected SHA-256 Merkle session roots. The expected
 * roots are computed HERE by a verbatim port of the worker's build_session_receipt
 * Merkle fold (mcp-apps-poc/worker.mjs, buildSessionReceiptCore, ~lines 2996-3020):
 *
 *   normalize(h)   = strip a leading 'sha256:' prefix, lowercase
 *   leaf           = 'sha256:' + normalize(h)
 *   pair(a, b)     = 'sha256:' + hex( SHA-256( normalize(a) + normalize(b) ) )
 *   odd level      = duplicate the LAST leaf
 *   root           = the single remaining level entry ('sha256:' + hex)
 *
 * Consumers:
 *   - site:  scripts/session-root-parity.test.mjs evaluates the generator-emitted
 *     ainSessionRoot routine (gen-webmcp-registrations.mjs SESSION_ROOT_SOURCE, the
 *     same bytes the bridge snippet v1.2 ships as window.AINBridge.sessionRoot)
 *     over these fixtures and asserts the expected roots.
 *   - worker: mcp-apps-poc/tests/chain-plan-and-session-root.test.mjs calls the REAL
 *     build_session_receipt tool (InMemoryTransport) over the vendored copy of this
 *     file and asserts the same roots. One fixture set, both runtimes, zero re-derivation.
 *
 * Modes:
 *   node scripts/gen-session-root-fixtures.mjs           # regenerate (deterministic; byte-stable)
 *   node scripts/gen-session-root-fixtures.mjs --check   # exit 1 if the committed file drifted
 *
 * Declared in scripts/derived-artifacts.mjs (id 'session-root-fixtures'); the worker
 * vendors the file through generate.mjs (D6: commit repo/data/ in the same push).
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const DATA_REL = 'data/session-root-fixtures.json';

// The Merkle fold, ported verbatim from worker.mjs buildSessionReceiptCore
// (node-side crypto instead of WebCrypto; the digest inputs are byte-identical).
const normalize = (h) => String(h).replace(/^sha256:/, '').toLowerCase();
const hex = (buf) => [...new Uint8Array(buf)].map((x) => x.toString(16).padStart(2, '0')).join('');
const hashPair = (a, b) =>
  'sha256:' + hex(createHash('sha256').update(normalize(a) + normalize(b), 'utf8').digest());
function sessionRoot(hashes) {
  if (!Array.isArray(hashes) || hashes.length === 0) throw new Error('execution_hashes must be a non-empty array.');
  let level = hashes.map(normalize).map((h) => 'sha256:' + h);
  while (level.length > 1) {
    const next = [];
    for (let i = 0; i < level.length; i += 2) {
      next.push(hashPair(level[i], level[i + 1] ?? level[i])); // duplicate last if odd
    }
    level = next;
  }
  return level[0];
}

// Deterministic fixture hash lists: fixed seed strings hashed to 64-hex leaves.
// No randomness, no clock: two runs produce byte-identical files.
const leaf = (s) => hex(createHash('sha256').update(s, 'utf8').digest());
const FixtureLists = [
  { name: 'single_leaf', seeds: ['ain-session-fixture:only'] },
  { name: 'two_leaves', seeds: ['ain-session-fixture:a', 'ain-session-fixture:b'] },
  { name: 'five_leaves_odd', seeds: ['ain-session-fixture:s1', 'ain-session-fixture:s2', 'ain-session-fixture:s3', 'ain-session-fixture:s4', 'ain-session-fixture:s5'] },
  { name: 'eight_leaves_full_binary', seeds: Array.from({ length: 8 }, (_, i) => 'ain-session-fixture:level' + i) },
  { name: 'prefixed_and_mixed_case', seeds: ['sha256:' + leaf('ain-session-fixture:prefixed').toUpperCase(), leaf('ain-session-fixture:plain')] },
  { name: 'chain_run_then_two_tools', seeds: [leaf('ain-session-fixture:plan'), leaf('ain-session-fixture:step1'), leaf('ain-session-fixture:step2'), leaf('ain-session-fixture:ledger')] },
];

const fixtures = FixtureLists.map((f) => {
  const execution_hashes = f.seeds.map(leaf);
  return { name: f.name, execution_hashes, expected_session_receipt_root: sessionRoot(execution_hashes) };
});

const body = JSON.stringify({
  _comment: 'Derived set (COMPOSER-PLAN-AND-ROOT-WEBMCP-1 parity gate B): ordered execution-hash lists with expected SHA-256 Merkle session receipts roots, port of worker.mjs buildSessionReceiptCore. Generated by scripts/gen-session-root-fixtures.mjs; the worker vendors this file via generate.mjs. Never hand-edit.',
  generated: 'scripts/gen-session-root-fixtures.mjs',
  fixture_count: fixtures.length,
  merkle_algorithm: 'SHA-256 binary tree, duplicate-last-leaf padding',
  fixtures,
}, null, 2) + '\n';

const outPath = resolve(REPO, DATA_REL);
if (process.argv.includes('--check')) {
  if (!existsSync(outPath) || readFileSync(outPath, 'utf8') !== body) {
    console.error(`✗ session-root-fixtures drifted — run: node scripts/gen-session-root-fixtures.mjs`);
    process.exit(1);
  }
  console.log(`✓ session-root-fixtures clean: ${fixtures.length} fixture hash list(s), expected roots byte-stable.`);
} else {
  writeFileSync(outPath, body);
  console.log(`wrote ${DATA_REL}: ${fixtures.length} fixture hash list(s) with expected roots.`);
}
