#!/usr/bin/env node
/**
 * check-branch-inventory.mjs — the consumer that makes REFUSAL-CARRYING EXCLUSIONS real.
 * Convention of record: chaingraph/standard/AUTHORING-STANDARD.md §1.
 *
 * WHY THIS SCRIPT IS THE WHOLE POINT. The research this convention was adopted from is blunt about
 * the failure mode it is trying to avoid: a declaration field that nothing consumes has no adversary
 * and decays into the appearance of assurance. So the branch inventory is not filed and forgotten —
 * every `refused` row is EXECUTED here. The gate imports the kernel, runs compute() on the row's own
 * declared reachability_vector, and requires the declared flag and payload marker to actually appear.
 * A refusal that does not fire is the excluded_branches[] failure mode wearing different clothes,
 * and it fails this gate.
 *
 * ⛔ NOTHING HERE IS SCHEMA. No SPEC.md section, no field in openchain-graph-v0.4.schema.json, no
 * node-shard member. An inventory is an authoring artifact under chaingraph/standard/, and the only
 * thing that reads it is this file.
 *
 * WHAT IT CHECKS, per inventory:
 *   1. Structure — tool_id matches the filename; a kernel exists for it; error_direction is one of
 *      the three closed values; every branch carries a unique id, a clause, and one of the four
 *      closed dispositions.
 *   2. INDEPENDENT DERIVATION (SO #34, AUTHORING-STANDARD §1.1) — every derived_from[].digest
 *      resolves to a real entry in chaingraph/standard/clause-snapshot-registry.json. An inventory
 *      is only as good as the primary text it was read from, and a digest that resolves to nothing
 *      means nobody can check that reading. ⛔ This is the reason the gate cannot accept a bare
 *      clause_path.
 *   3. REACHABILITY (§1.3) — for each `refused` row: compute(reachability_vector) must put
 *      refusal.flag in compliance_flags AND make refusal.payload_marker truthy in output_payload,
 *      and refusal.fixture must name a vector that exists.
 *   4. REPRESENTATION EVIDENCE — for each `represented` row: the named evidence member must appear
 *      in output_payload on at least one observed run. This is deliberately weak (a member can be
 *      present and wrong) and it is the only consumer `represented` has; see AUTHORING-STANDARD §5.6
 *      on why that asymmetry is inherent rather than an oversight here.
 *   5. ASSUMPTIONS OF USE — each `out_of_scope_by_input` row names the value, its source, and the
 *      party who owns supplying it correctly. A relocated assertion with no named owner is an
 *      assertion that stopped being anybody's job.
 *   6. `unrepresented_known` rows require a declared error_direction on the branch. They are
 *      FINDINGS, counted and reported, never scored as fill quality — a row is not "done" because
 *      the author admitted the gap.
 *
 * Usage:
 *   node scripts/check-branch-inventory.mjs             # gate over every inventory
 *   node scripts/check-branch-inventory.mjs <tool_id>   # one
 *   node scripts/check-branch-inventory.mjs --metrics   # + the fill-quality measurement
 */
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const DISPOSITIONS = Object.freeze(['represented', 'refused', 'out_of_scope_by_input', 'unrepresented_known']);
export const ERROR_DIRECTIONS = Object.freeze(['conservative_toward_finding', 'conservative_toward_no_finding', 'undirected']);

function truthy(v) {
  if (Array.isArray(v)) return v.length > 0;
  if (typeof v === 'number') return v > 0;
  return Boolean(v);
}

function registryDigests(repo) {
  const p = resolve(repo, 'chaingraph', 'standard', 'clause-snapshot-registry.json');
  if (!existsSync(p)) return null;
  const parsed = JSON.parse(readFileSync(p, 'utf8'));
  const rows = Array.isArray(parsed) ? parsed : (parsed.snapshots || parsed.entries || Object.values(parsed).find(Array.isArray) || []);
  return new Set(rows.map((r) => r.digest).filter(Boolean));
}

/**
 * A refusal's fixture may live in EITHER of two files, and the split is load-bearing
 * (AUTHORING-STANDARD.md §1.5):
 *   <tool_id>.fixtures.json      conformance vectors. Some nodes' property floors require EVERY
 *                                vector here to carry an independent_oracle — art-637's floor says
 *                                so in as many words ("the fixture would be its own oracle").
 *   <tool_id>.reachability.json  reachability vectors, kernel_generated by construction.
 * Putting a reachability vector in the first file would weaken a node's own conformance floor to
 * accommodate a demonstration about the code. Measured: doing exactly that turned art-637's floor
 * red on three vectors, which is how this separation was found.
 *
 * @returns {Map<string, object>} vector name -> vector, across both files.
 */
function fixtureVectors(repo, toolId) {
  const out = new Map();
  let sawFile = false;
  for (const suffix of ['fixtures', 'reachability']) {
    const p = resolve(repo, 'chaingraph', 'kernels', 'fixtures', `${toolId}.${suffix}.json`);
    if (!existsSync(p)) continue;
    sawFile = true;
    let parsed;
    try { parsed = JSON.parse(readFileSync(p, 'utf8')); } catch { continue; }
    const vectors = Array.isArray(parsed) ? parsed : (parsed.vectors || parsed.cases || parsed.fixtures || []);
    for (const v of vectors || []) if (v && (v.name || v.id)) out.set(v.name || v.id, v);
  }
  return sawFile ? out : null;
}

/** Every observed output_payload key across the kernel's fixture vectors plus {}. */
function observedPayloadKeys(compute, repo, toolId) {
  const p = resolve(repo, 'chaingraph', 'kernels', 'fixtures', `${toolId}.fixtures.json`);
  const inputs = [{}];
  if (existsSync(p)) {
    try {
      const parsed = JSON.parse(readFileSync(p, 'utf8'));
      const vectors = Array.isArray(parsed) ? parsed : (parsed.vectors || parsed.cases || parsed.fixtures || []);
      for (const v of vectors || []) if (v && v.policy_parameters) inputs.push(v.policy_parameters);
    } catch { /* an unreadable fixture file is reported by check 3, not here */ }
  }
  const keys = new Set();
  for (const pp of inputs) {
    try { for (const k of Object.keys(compute(structuredClone(pp))?.output_payload || {})) keys.add(k); } catch { /* skip */ }
  }
  return keys;
}

export async function checkInventory(inv, { repo = REPO, digests = null } = {}) {
  const errors = [];
  const counts = { represented: 0, refused: 0, out_of_scope_by_input: 0, unrepresented_known: 0 };
  const confirmed = { represented: 0, refused: 0, out_of_scope_by_input: 0 };
  const id = inv.tool_id;

  if (!ERROR_DIRECTIONS.includes(inv.error_direction)) {
    errors.push(`error_direction "${inv.error_direction}" is not one of ${ERROR_DIRECTIONS.join(' | ')}`);
  }
  if (inv.error_direction && inv.error_direction !== 'undirected' && !inv.error_direction_rationale) {
    errors.push('a directed error_direction requires error_direction_rationale');
  }
  for (const d of inv.derived_from || []) {
    if (digests && !digests.has(d.digest)) errors.push(`derived_from digest ${String(d.digest).slice(0, 20)}… does not resolve in clause-snapshot-registry.json`);
  }
  if (!Array.isArray(inv.derived_from) || inv.derived_from.length === 0) {
    errors.push('derived_from[] is empty — an inventory read from the kernel instead of the primary text is void (SO #34)');
  }

  let compute = null;
  try { ({ compute } = await import(pathToFileURL(resolve(repo, 'chaingraph', 'kernels', `${id}.kernel.mjs`)).href)); } catch { /* reported below */ }
  if (typeof compute !== 'function') {
    errors.push(`no callable compute() for ${id} — every reachability claim in this inventory is UNVERIFIED, not passing (SO #34c)`);
    return { tool_id: id, errors, counts, confirmed };
  }

  const payloadKeys = observedPayloadKeys(compute, repo, id);
  const vectors = fixtureVectors(repo, id);
  const seen = new Set();

  for (const b of inv.branches || []) {
    if (!b.id) { errors.push('a branch has no id'); continue; }
    if (seen.has(b.id)) errors.push(`duplicate branch id "${b.id}"`);
    seen.add(b.id);
    if (!b.clause) errors.push(`${b.id}: no clause locator`);
    if (!DISPOSITIONS.includes(b.disposition)) { errors.push(`${b.id}: disposition "${b.disposition}" is not one of ${DISPOSITIONS.join(' | ')}`); continue; }
    counts[b.disposition]++;

    if (b.disposition === 'refused') {
      const r = b.refusal || {};
      if (!r.flag || !r.payload_marker || !r.reachability_vector) { errors.push(`${b.id}: refused requires refusal.{flag,payload_marker,reachability_vector}`); continue; }
      let out;
      try { out = compute(structuredClone(r.reachability_vector)); } catch (e) { errors.push(`${b.id}: reachability_vector threw — ${e.message}`); continue; }
      const flags = Array.isArray(out?.compliance_flags) ? out.compliance_flags : [];
      const payload = out?.output_payload || {};
      let ok = true;
      if (!flags.includes(r.flag)) { errors.push(`${b.id}: UNREACHABLE — flag "${r.flag}" not raised (got [${flags.join(', ')}])`); ok = false; }
      if (!truthy(payload[r.payload_marker])) { errors.push(`${b.id}: UNREACHABLE — payload marker "${r.payload_marker}" not truthy`); ok = false; }
      if (!r.fixture) { errors.push(`${b.id}: refused requires refusal.fixture naming the vector that exercises it`); ok = false; }
      else {
        const vec = String(r.fixture).split('#')[1];
        if (vectors === null) { errors.push(`${b.id}: no fixtures file for ${id}`); ok = false; }
        else if (!vec || !vectors.has(vec)) { errors.push(`${b.id}: fixture vector "${vec ?? ''}" not found in ${id}.fixtures.json or ${id}.reachability.json`); ok = false; }
        else {
          // A reachability vector must BE the vector the inventory declares. Without this the two
          // can drift into agreeing about nothing: the gate would run one input and the estate's
          // fixture would pin another.
          const fx = vectors.get(vec);
          if (fx.provenance === 'kernel_generated' && JSON.stringify(fx.policy_parameters) !== JSON.stringify(r.reachability_vector)) {
            errors.push(`${b.id}: reachability vector "${vec}" does not match the inventory's reachability_vector`);
            ok = false;
          }
        }
      }
      if (ok) confirmed.refused++;
    } else if (b.disposition === 'represented') {
      if (!b.evidence) { errors.push(`${b.id}: represented requires evidence naming the output_payload member that carries it`); continue; }
      if (!payloadKeys.has(b.evidence)) errors.push(`${b.id}: evidence member "${b.evidence}" never appears in output_payload across the observed inputs`);
      else confirmed.represented++;
    } else if (b.disposition === 'out_of_scope_by_input') {
      const a = b.assumption_of_use || {};
      if (!a.value || !a.source || !a.owner) errors.push(`${b.id}: out_of_scope_by_input requires assumption_of_use.{value,source,owner} — a relocated assertion with no named owner is nobody's job`);
      else confirmed.out_of_scope_by_input++;
    } else if (b.disposition === 'unrepresented_known') {
      if (!ERROR_DIRECTIONS.includes(b.error_direction)) errors.push(`${b.id}: unrepresented_known requires a declared error_direction (${ERROR_DIRECTIONS.join(' | ')})`);
    }
  }
  return { tool_id: id, errors, counts, confirmed };
}

export async function run({ repo = REPO, argv = [] } = {}) {
  const dir = resolve(repo, 'chaingraph', 'standard', 'branch-inventories');
  const metrics = argv.includes('--metrics');
  const only = argv.find((a) => !a.startsWith('--'));
  if (!existsSync(dir)) { console.error(`✗ no branch-inventories directory at ${dir}`); return 1; }

  const digests = registryDigests(repo);
  if (digests === null) { console.error('✗ clause-snapshot-registry.json missing — cannot verify independent derivation'); return 1; }

  const files = readdirSync(dir).filter((f) => f.endsWith('.inventory.json')).sort();
  const reports = [];
  for (const f of files) {
    const inv = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    const expected = f.replace(/\.inventory\.json$/, '');
    if (inv.tool_id !== expected) { console.error(`✗ ${f}: tool_id "${inv.tool_id}" does not match filename`); return 1; }
    if (only && inv.tool_id !== only) continue;
    reports.push(await checkInventory(inv, { repo, digests }));
  }

  const total = { represented: 0, refused: 0, out_of_scope_by_input: 0, unrepresented_known: 0 };
  const conf = { represented: 0, refused: 0, out_of_scope_by_input: 0 };
  let failed = 0;
  console.log('BRANCH INVENTORY — refusal-carrying exclusions (AUTHORING-STANDARD.md §1)');
  for (const r of reports) {
    const n = Object.values(r.counts).reduce((a, b) => a + b, 0);
    console.log(`  ${r.errors.length === 0 ? '✓' : '✗'} ${r.tool_id.padEnd(48)} ${String(n).padStart(3)} branches  represented ${r.counts.represented} · refused ${r.counts.refused} · by-input ${r.counts.out_of_scope_by_input} · UNREPRESENTED ${r.counts.unrepresented_known}`);
    for (const e of r.errors) { console.error(`      ✗ ${e}`); failed++; }
    for (const k of Object.keys(total)) total[k] += r.counts[k];
    for (const k of Object.keys(conf)) conf[k] += r.confirmed[k];
  }

  if (metrics) {
    const scored = total.represented + total.refused + total.out_of_scope_by_input;
    const confirmedTotal = conf.represented + conf.refused + conf.out_of_scope_by_input;
    const branches = scored + total.unrepresented_known;
    const pct = (a, b) => (b === 0 ? 'n/a' : `${((a / b) * 100).toFixed(1)}%`);
    console.log('\nFILL QUALITY — the share of inventory rows whose declared disposition is CONFIRMED BY');
    console.log('EXECUTING THE KERNEL. `unrepresented_known` rows are findings: counted, never scored');
    console.log('(a row is not "done" because the author admitted the gap).');
    console.log(`  nodes inventoried                       ${reports.length}`);
    console.log(`  branches enumerated from primary text   ${branches}`);
    console.log(`  refusal reachability   ${String(conf.refused).padStart(3)} / ${String(total.refused).padEnd(3)}  ${pct(conf.refused, total.refused)}   (refused rows whose declared path actually fires)`);
    console.log(`  representation evidence${String(conf.represented).padStart(4)} / ${String(total.represented).padEnd(3)}  ${pct(conf.represented, total.represented)}   (represented rows whose named payload member appears)`);
    console.log(`  assumptions of use     ${String(conf.out_of_scope_by_input).padStart(3)} / ${String(total.out_of_scope_by_input).padEnd(3)}  ${pct(conf.out_of_scope_by_input, total.out_of_scope_by_input)}   (by-input rows naming value + source + owner)`);
    console.log(`  FILL QUALITY           ${String(confirmedTotal).padStart(3)} / ${String(scored).padEnd(3)}  ${pct(confirmedTotal, scored)}`);
    console.log(`  UNREPRESENTED (findings, unscored)      ${total.unrepresented_known}  ${pct(total.unrepresented_known, branches)} of all branches`);
  }

  if (failed) { console.error(`\n✗ ${failed} inventory defect(s).`); return 1; }
  console.log('\n✓ every declared refusal fires; every declared representation is present.');
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exit(await run({ argv: process.argv.slice(2) }));
}
